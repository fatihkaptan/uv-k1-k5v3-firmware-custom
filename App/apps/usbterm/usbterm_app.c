/*
 * USB Term - a text terminal between the radio and a computer over the USB-C
 * serial port (API level 3, serial_*, APP_CAP_SERIAL). No RF: nothing is ever
 * transmitted. See README.md.
 *
 * Computer -> radio: every byte the computer sends is shown on the radio, a
 * line at a time, in the 3x5 font (32 columns, 6 rows, 32 rows of scrollback).
 * CR, LF or CR LF end a line; backspace deletes; ANSI escape sequences (the
 * arrow keys of a terminal) are skipped; the two-byte UTF-8 letters of Turkish
 * (and a few others) become their ASCII base letter. A whole line "/<command>"
 * is a command (/help /info /ping /beep /clear /echo on /echo off), answered
 * with lines that start with "# " and not shown on the radio.
 *
 * Echo (on by default, and again at each new connection): the radio sends back
 * what it receives, so a plain serial terminal (PuTTY, screen, minicom,
 * miniterm) shows what is typed, like a console. A line-mode client (the
 * uvterm.py companion) sends "/echo off" first.
 *
 * Radio -> computer: a line typed on the keypad (multi-tap, like a phone) is
 * sent with CR LF when MENU is pressed, and shown on the radio as "> text".
 * It is typed in the 6x7 font, on the two bottom lines (18 columns each).
 *
 * Keys: 0-9 multi-tap (hold: the digit) · * abc / ABC / 123 · MENU send ·
 * EXIT delete (hold: clear the line; on an empty line: quit) · UP / DOWN
 * scroll back (hold: repeat) · F notification beep on / off (saved).
 */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../app_api.h"
#include "usbterm_assets.h"     /* generated by gen_assets.py */

#define COLS      32u     /* 3x5 font, 4 px per character: 128 px              */
#define VROWS     6u      /* history rows on screen: y 0..35, 6 px apart       */
#define HROWS     32u     /* scrollback ring (power of two), on app_main's stack */
#define IN_MAX    64u     /* line typed on the keypad                          */
#define IN_COLS   18u     /* keypad line: 6x7 font, 7 px per character ...     */
#define IN_LINE   5u      /* ... on frame lines 5 and 6, below a rule at y 37  */
#define TX_MAX    64u     /* bytes per serial_write                            */
#define POLL_MS   10u
#define TAP_MS    900u    /* same key again within this: next letter           */
#define LONG_MS   700u    /* long press                                        */
#define REP_MS    120u    /* scroll repeat while UP / DOWN is held             */
#define LED_MS    80u
#define REDRAW_MS 5000u   /* status line (battery) refresh                     */
#define BEEP_HZ   1200u
#define BEEP_MS   40u
#define ERR_HZ    300u
#define ERR_MS    120u
#define CFG_MAGIC 0x54u   /* 'T' */

enum { M_LOW, M_UP, M_NUM, M_COUNT };
/* Same order as CMDS / T_RESP in gen_assets.py. */
enum { C_HELP, C_INFO, C_PING, C_BEEP, C_CLEAR, C_ECHO_ON, C_ECHO_OFF, C_COUNT };

typedef struct { uint8_t magic, mode, sound; } cfg_t;   /* saved by cfg_save */

/* All the state, bytes first (Thumb immediate ranges). The loader zeroes the
 * overlay at each launch. */
static struct {
    uint8_t  head, count, scroll;      /* history ring                         */
    uint8_t  inLen, rxLen, txLen;      /* keypad line, computer line, tx bytes */
    uint8_t  utf8, esc;                /* receive decoder state                */
    uint8_t  tapKey, tapIdx;           /* multi-tap                            */
    uint8_t  raw, key;                 /* last reading, debounced key held     */
    uint8_t  lost;                     /* receive ring overruns (/info)        */
    bool     tap, held, echo, host, dirty, quit, cr, led, saver, txOk;
    cfg_t    cfg;
    const app_api_t *A;
    char   (*hist)[COLS];              /* HROWS rows                           */
    uint32_t now, tapT, keyT, repT, ledT, drawT;
    char     in[IN_MAX + 1];
    char     rx[COLS + 1];
    uint8_t  tx[TX_MAX];
} g;

/* ---- freestanding helpers GCC may call (the host test uses the C library's) ---- */
#ifndef HOST_TEST
void *memset(void *d, int c, size_t n) {
    uint8_t *p = d; while (n) p[--n] = (uint8_t)c; return d;
}
void *memcpy(void *d, const void *s, size_t n) {
    uint8_t *p = d; const uint8_t *q = s;
    while (n) { --n; p[n] = q[n]; } return d;
}
#endif

/* An asset text into buf (TEXT_MAX bytes). */
static char *T(char *buf, uint16_t off) { g.A->asset_read(off, buf, TEXT_MAX); return buf; }

/* ---- serial out: buffered, sent in TX_MAX-byte writes. txOk drops to false
 * when a write fails (no host has the port open, or it did not read). ---- */
static void flush(void) {
    if (g.txLen && !g.A->serial_write(APP_SERIAL_USB, g.tx, g.txLen)) g.txOk = false;
    g.txLen = 0;
}
static void outc(char c) {
    if (g.txLen >= TX_MAX) flush();
    g.tx[g.txLen++] = (uint8_t)c;
}
static void outn(const char *s, uint8_t n) { for (uint8_t i = 0; i < n; i++) outc(s[i]); }
static void outs(const char *s) { while (*s) outc(*s++); }
static void outnl(void) { outc('\r'); outc('\n'); }
static void outT(uint16_t off) { char t[TEXT_MAX]; outs(T(t, off)); }
static void outLine(uint16_t off) { outT(off); outnl(); }
/* u as decimal; with digits > 0, exactly that many digits (leading zeros). */
static void outU(uint32_t u, uint8_t digits) {
    char t[12];
    static const uint32_t pow10[] = { 1u, 10u, 100u, 1000u, 10000u, 100000u };
    char *e = g.A->append_u32(t, digits ? u + pow10[digits] : u);
    *e = '\0';
    outs(digits ? t + 1 : t);
}

/* ---- sounds and indicator ---- */
static void beep(void) { g.A->play_tone(BEEP_HZ, BEEP_MS); }
static void errBeep(void) { g.A->play_tone(ERR_HZ, ERR_MS); }
static void notify(void) {
    g.A->backlight_on();                 /* also leaves the screen saver */
    g.A->led(true); g.led = true; g.ledT = g.now;
    if (g.cfg.sound) beep();
}

/* ---- history: a ring of COLS-character rows, NUL-padded ---- */
static void addRow(const char *s, uint8_t n) {
    char *r = g.hist[g.head];
    for (uint8_t i = 0; i < COLS; i++) r[i] = i < n ? s[i] : '\0';
    g.head = (uint8_t)((g.head + 1u) & (HROWS - 1u));
    if (g.count < HROWS) g.count++;
    g.scroll = 0;
    g.dirty = true;
}
static void addText(const char *s, uint8_t n) {        /* wrapped at COLS */
    while (n) {
        uint8_t k = n > COLS ? COLS : n;
        addRow(s, k); s += k; n = (uint8_t)(n - k);
    }
}

/* ---- commands from the computer ---- */
static bool eqi(const char *a, const char *b) {         /* b is lower case */
    for (;;) {
        char x = *a++, y = *b++;
        if (x >= 'A' && x <= 'Z') x = (char)(x + 32);
        if (x != y) return false;
        if (!x) return true;
    }
}

static void info(void) {
    const app_api_t *A = g.A;
    outT(T_INFO);
    if (A->sys_version && A->sys_edition) {              /* Labs system information */
        outT(T_FW); outs(A->sys_edition); outc(' '); outs(A->sys_version);
    }
    outnl();
    /* "# RX 145.50000 MHz  -97 dBm" (rx_freq in 10 Hz units) */
    uint64_t q = A->uidivmod(A->rx_freq(), 100000u);
    outT(T_RX); outU((uint32_t)q, 0); outc('.'); outU((uint32_t)(q >> 32), 5);
    outT(T_MHZ);
    { char t[12]; *A->append_i32(t, A->rssi_dbm()) = '\0'; outs(t); }
    outLine(T_DBM);
    /* "# BAT 7.85 V  lost 0" (10 mV units) */
    outT(T_BAT);
    if (A->sys_battery_voltage) {
        q = A->uidivmod(*A->sys_battery_voltage, 100u);
        outU((uint32_t)q, 0); outc('.'); outU((uint32_t)(q >> 32), 2);
    } else outc('?');
    outT(T_VOLT); outT(T_LOST); outU(g.lost, 0); outnl();
}

/* A complete line from the computer that starts with '/': true when it was
 * one of the commands (then run, answered and not shown). */
static bool command(void) {
    char c[CMDS_STRIDE];
    for (uint8_t k = 0; k < C_COUNT; k++) {
        g.A->asset_read((uint16_t)(CMDS + k * CMDS_STRIDE), c, CMDS_STRIDE);
        if (!eqi(g.rx + 1, c)) continue;
        switch (k) {
        case C_HELP:  outLine(T_HELP1); outLine(T_HELP2); break;
        case C_INFO:  info(); break;
        case C_CLEAR: g.count = 0; g.scroll = 0; break;
        case C_ECHO_ON:
        case C_ECHO_OFF: g.echo = (k == C_ECHO_ON); break;
        default: break;
        }
        if (k >= C_PING) outLine((uint16_t)(T_RESP + k * T_RESP_STRIDE));
        if (k == C_BEEP) { flush(); beep(); }
        return true;
    }
    return false;
}

/* ---- computer -> radio decoder ---- */
static void rxCommit(void) {                             /* end of line */
    if (g.rxLen) {
        g.rx[g.rxLen] = '\0';
        if (g.rx[0] != '/' || !command()) { addRow(g.rx, g.rxLen); notify(); }
    }
    g.rxLen = 0;
    g.dirty = true;
}
static void rxChar(char c) {
    if (g.rxLen >= COLS) { addRow(g.rx, COLS); g.rxLen = 0; }   /* wrap */
    g.rx[g.rxLen++] = c;
    g.dirty = true;
}
static char translit(uint8_t lead, uint8_t cont) {
    uint8_t t[TRL_LEN];
    g.A->asset_read(TRL, t, TRL_LEN);
    for (uint8_t i = 0; i < TRL_LEN; i += 3)
        if (t[i] == lead && t[i + 1] == cont) return (char)t[i + 2];
    return '?';
}
static void rxByte(uint8_t b) {
    if (g.esc) {                         /* ESC [ params final, ESC O x, ESC x */
        if (g.esc == 1) g.esc = (b == '[' || b == 'O') ? 2 : 0;
        else if (b >= 0x40 && b <= 0x7E) g.esc = 0;
        return;
    }
    if (b >= 0x80) {                     /* UTF-8: echoed as is, shown in ASCII */
        if (g.echo) outc((char)b);
        if (b >= 0xC0) g.utf8 = b;
        else if (g.utf8) { rxChar(translit(g.utf8, b)); g.utf8 = 0; }
        return;
    }
    g.utf8 = 0;
    const bool cr = g.cr;
    g.cr = false;
    if (b == '\r' || b == '\n') {
        if (b == '\n' && cr) return;     /* CR LF: one end of line */
        g.cr = (b == '\r');
        if (g.echo) outnl();
        rxCommit();
        return;
    }
    if (b == 8 || b == 127) {            /* backspace */
        if (g.rxLen) {
            g.rxLen--; g.dirty = true;
            if (g.echo) { outc(8); outc(' '); outc(8); }
        }
        return;
    }
    if (b == 27) { g.esc = 1; return; }
    if (b == '\t') b = ' ';
    if (b < ' ') return;
    if (g.echo) outc((char)b);
    rxChar((char)b);
}
static void serialPoll(void) {
    uint8_t buf[32];
    for (uint8_t rep = 0; rep < 8u; rep++) {   /* at most the whole 256-byte ring */
        uint16_t n = g.A->serial_read(APP_SERIAL_USB, buf, sizeof buf);
        if (!n) break;
        for (uint16_t i = 0; i < n; i++) rxByte(buf[i]);
    }
    flush();
}

/* ---- USB link state: a new connection gets the banner and echo back on ---- */
static void usb(void) {
    const uint8_t st = g.A->serial_ctl(APP_SERIAL_USB, 0);
    const bool h = (st & APP_SERIAL_HOST) != 0;
    if (st & APP_SERIAL_LOST) g.lost++;
    if (h == g.host) return;
    g.host = h;
    g.dirty = true;
    if (h) { g.echo = true; outLine(T_BANNER); flush(); }
}

/* ---- radio -> computer: the keypad line ---- */
static void sendLine(void) {
    if (!g.inLen) return;
    const bool reecho = g.echo && g.rxLen;  /* a raw terminal is mid-line */
    g.txOk = true;
    if (reecho) outnl();
    outn(g.in, g.inLen); outnl();
    if (reecho) outn(g.rx, g.rxLen);       /* its partial line, back under ours */
    flush();
    if (!g.txOk) { g.host = false; errBeep(); return; }   /* the line is kept */
    char row[IN_MAX + 2];
    row[0] = '>'; row[1] = ' ';
    for (uint8_t i = 0; i < g.inLen; i++) row[2 + i] = g.in[i];
    addText(row, (uint8_t)(g.inLen + 2u));
    g.inLen = 0;
}

/* ---- keypad ---- */
static bool ins(char c) {
    if (g.inLen >= IN_MAX) { errBeep(); return false; }
    g.in[g.inLen++] = c;
    return true;
}
static char cased(char c) {
    return (g.cfg.mode == M_UP && c >= 'a' && c <= 'z') ? (char)(c - 32) : c;
}
static void typeKey(uint8_t k) {
    if (g.cfg.mode == M_NUM) { g.tap = false; ins((char)('0' + k)); return; }
    char m[KEYMAP_STRIDE];
    g.A->asset_read((uint16_t)(KEYMAP + k * KEYMAP_STRIDE), m, KEYMAP_STRIDE);
    if (g.tap && g.tapKey == k) {        /* same key again: next letter */
        if (!m[++g.tapIdx]) g.tapIdx = 0;
        g.in[g.inLen - 1] = cased(m[g.tapIdx]);
    } else {
        g.tap = false;
        if (!ins(cased(m[0]))) return;
        g.tap = true; g.tapKey = k; g.tapIdx = 0;
    }
    g.tapT = g.now;
}
/* Rows on screen: the history, then the computer's unfinished line. */
static uint8_t total(void) { return (uint8_t)(g.count + (g.rxLen ? 1u : 0u)); }
/* The furthest g.scroll may go back; also pulls g.scroll in when the rows
 * shrank under it (a command line or a backspace ends the unfinished line). */
static uint8_t maxScroll(void) {
    const uint8_t t = total();
    const uint8_t max = t > VROWS ? (uint8_t)(t - VROWS) : 0;
    if (g.scroll > max) g.scroll = max;
    return max;
}
static void scroll(uint8_t k) {
    const uint8_t max = maxScroll();
    if (k == APP_KEY_UP) { if (g.scroll < max) g.scroll++; }
    else if (g.scroll) g.scroll--;
    g.dirty = true;
}
static void onPress(uint8_t k) {
    g.dirty = true;
    if (k <= APP_KEY_9) { typeKey(k); return; }
    g.tap = false;
    switch (k) {
    case APP_KEY_MENU: sendLine(); break;
    case APP_KEY_EXIT: if (g.inLen) g.inLen--; else g.quit = true; break;
    case APP_KEY_STAR: if (++g.cfg.mode >= M_COUNT) g.cfg.mode = M_LOW; break;
    case APP_KEY_F:    g.cfg.sound ^= 1u; if (g.cfg.sound) beep(); break;
    case APP_KEY_UP:
    case APP_KEY_DOWN: scroll(k); break;
    default: break;
    }
}
static void onLong(uint8_t k) {
    if (k <= APP_KEY_9) {
        if (g.tap && g.tapKey == k) {    /* the letter this press typed -> digit */
            g.in[g.inLen - 1] = (char)('0' + k);
            g.tap = false; g.dirty = true;
        }
    } else if (k == APP_KEY_EXIT) { g.inLen = 0; g.dirty = true; }
}
static void keys(void) {
    const uint8_t k = g.A->get_key();
    if (k == APP_KEY_SAVER) { g.saver = true; return; }
    g.saver = false;
    if (k == APP_KEY_WAKE) { g.dirty = true; g.raw = g.key = APP_KEY_INVALID; return; }
    if (k != g.raw) { g.raw = k; return; }      /* debounce: two equal readings */
    if (k == g.key) {                           /* still held */
        if (k == APP_KEY_INVALID) return;
        if (!g.held) {
            if (g.now - g.keyT >= LONG_MS) { g.held = true; g.repT = g.now; onLong(k); }
        } else if ((k == APP_KEY_UP || k == APP_KEY_DOWN) && g.now - g.repT >= REP_MS) {
            g.repT = g.now; scroll(k);
        }
        return;
    }
    g.key = k; g.held = false; g.keyT = g.now;
    if (k != APP_KEY_INVALID) onPress(k);
}

/* ---- screen ---- */
__attribute__((noinline))
static void draw(void) {
    const app_api_t *A = g.A;
    char t[TEXT_MAX], s[COLS + 1];
    A->display_clear();
    A->status_clear();

    /* status line: TERM, USB / NO USB, input mode, BEEP, ^scroll, battery */
    A->print_inverse(T(t, T_TITLE), 2, 0, true, true, 18);
    T(t, (uint16_t)(T_CAPS + (g.host ? 0u : T_CAPS_STRIDE)));
    { uint8_t w = 0; while (t[w]) w++;
      A->print_inverse(t, 24, 0, true, true, (uint8_t)(24u + 4u * w)); }
    A->print_tiny(T(t, (uint16_t)(T_MODES + g.cfg.mode * T_MODES_STRIDE)), 52, 1, true, true);
    if (g.scroll) {                     /* rows scrolled back, in BEEP's place */
        s[0] = '^'; *A->append_u32(s + 1, g.scroll) = '\0';
        A->print_tiny(s, 66, 1, true, true);
    } else if (g.cfg.sound) A->print_tiny(T(t, T_SOUND), 66, 1, true, true);
    A->draw_battery();

    /* history: the last VROWS rows (the computer's unfinished line last),
     * g.scroll rows back */
    const uint8_t base = (uint8_t)(maxScroll() - g.scroll);
    const uint8_t rows = total();
    for (uint8_t r = 0; r < VROWS; r++) {
        const uint8_t i = (uint8_t)(base + r);
        if (i >= rows) break;
        const char *src = g.rx;
        uint8_t n = g.rxLen;
        if (i < g.count) { src = g.hist[(g.head - g.count + i) & (HROWS - 1u)]; n = COLS; }
        uint8_t j = 0;
        for (; j < n && src[j]; j++) s[j] = src[j];
        s[j] = '\0';
        A->print_tiny(s, 0, (uint8_t)(r * 6u), false, true);
    }

    /* a rule (y 37), then the keypad line in the 6x7 font: the two lines of
     * IN_COLS that hold the cursor (the text moves up a line when the second
     * one is full). The cursor is a block that XORs over a letter still open
     * to multi-tap, which then shows inverted. */
    for (uint8_t x = 0; x < 128u; x++) A->fb[4][x] |= 0x20u;
    const uint8_t cur = (uint8_t)(g.inLen - (g.tap ? 1u : 0u));
    uint8_t first = 0;
    while (cur >= first + 2u * IN_COLS) first = (uint8_t)(first + IN_COLS);
    for (uint8_t l = 0; l < 2u; l++) {
        const uint8_t a = (uint8_t)(first + l * IN_COLS);
        uint8_t j = 0;
        for (; j < IN_COLS && a + j < g.inLen; j++) s[j] = g.in[a + j];
        s[j] = '\0';
        A->print_normal(s, 0, 0, (uint8_t)(IN_LINE + l));
    }
    uint8_t c = (uint8_t)(cur - first), line = IN_LINE;
    if (c >= IN_COLS) { c = (uint8_t)(c - IN_COLS); line++; }
    uint8_t *p = A->fb[line] + c * 7u;              /* glyph c: x 7c+1 .. 7c+6 */
    for (uint8_t i = 0; i < 7u; i++) p[i] ^= 0x7Fu;

    A->blit_status();
    A->blit_full();
}

__attribute__((section(".text.entry"), used))
void app_main(const app_api_t *api) {
    char hist[HROWS][COLS];             /* on the stack: the overlay holds the code */
    g.A = api; g.hist = hist;
    g.raw = g.key = APP_KEY_INVALID;
    g.echo = true;
    api->cfg_load((uint8_t *)&g.cfg, sizeof g.cfg);
    if (g.cfg.magic != CFG_MAGIC || g.cfg.mode >= M_COUNT) {
        g.cfg.magic = CFG_MAGIC; g.cfg.mode = M_LOW; g.cfg.sound = 1u;
    }
    g.cfg.sound &= 1u;
    api->backlight_on();
    g.dirty = true;

    while (!g.quit) {
        g.now = api->ticks_ms();
        usb();
        serialPoll();
        keys();
        if (g.tap && g.now - g.tapT >= TAP_MS) { g.tap = false; g.dirty = true; }
        if (g.led && g.now - g.ledT >= LED_MS) { g.led = false; api->led(false); }
        if (g.now - g.drawT >= REDRAW_MS) { api->battery_sample(); g.dirty = true; }
        api->backlight_update();
        if (g.dirty && !g.saver) { g.dirty = false; g.drawT = g.now; draw(); }
        api->delay_ms(POLL_MS);
    }
    api->led(false);
    api->cfg_save((const uint8_t *)&g.cfg, sizeof g.cfg);
}
