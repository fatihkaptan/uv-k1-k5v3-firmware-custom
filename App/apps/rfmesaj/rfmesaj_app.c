/*
 * RF Mesaj - text messages between radios that run this app, over the air on
 * the current VFO: the BK4819 FSK modem at 1200 bps (the register sequences
 * of the BEAM app), one 72-byte packet per message. See README.md.
 *
 * Packet: magic, flags, seq, a random nonce, the sender's callsign (from the
 * power-on message: every packet identifies its station), 48 text bytes, a
 * 32-bit tag, CRC-16, tail. The tag is an XTEA CBC-MAC under the group key,
 * derived from a passphrase both radios share (F+2): a message from a radio
 * with another key shows with '?'. Optionally (F+1, GIZLI) the text is
 * encrypted with XTEA in counter mode, encrypt-then-MAC. Encryption that hides
 * the meaning is not allowed on amateur bands (ITU RR 25.2A): GIZLI is off by
 * default and announces it.
 *
 * Every message with a good tag is acknowledged after a random 150-550 ms;
 * the sender tries 3 times, 3 s apart, and shows who received it. Repeats are
 * recognised (sender, seq) and only acknowledged again.
 *
 * USB: the computer's lines are sent over the air, received messages and
 * the "# ..." status lines go to the computer (a bridge to the outside world,
 * tools/rfmesaj/rfkopru.py). /echo off answers like USB Term, so uvterm.py
 * chats too; /key <passphrase> sets the key. The computer sends ASCII
 * (rfkopru.py turns Turkish letters into c g i o s u).
 */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../app_api.h"
#include "rfmesaj_assets.h"     /* generated by gen_assets.py */

#define COLS      32u     /* history: 3x5 font, 32 columns ...                 */
#define VROWS     6u      /* ... 6 rows on screen                              */
#define HROWS     32u     /* scrollback ring, on app_main's stack              */
#define IN_MAX    48u     /* one message: the packet's text field              */
#define IN_COLS   18u     /* keypad line: 6x7 font, two lines                  */
#define IN_LINE   5u
#define TX_MAX    64u
#define POLL_MS   10u
#define TAP_MS    900u
#define LONG_MS   700u
#define REDRAW_MS 5000u
#define ACK_MS    3000u   /* wait for an acknowledgement ...                   */
#define TRIES     3u      /* ... this many transmissions                       */
#define MAGIC     0x4D52u /* "RM"                                              */
#define TAIL      0xDCBAu
#define PKT_WORDS 36u
#define P_ENC     0x01u   /* packet flags                                      */
#define P_ACK     0x02u
#define CFG_MAGIC 0x52u
#define CF_KEY    0x01u   /* cfg flags: a key is set ...                       */
#define CF_ENC    0x02u   /* ... GIZLI ...                                     */
#define CF_MUTE   0x04u   /* ... no notification beep                          */
#define REG_02    0x02
#define REG_0B    0x0B
#define REG_0C    0x0C
#define REG_5F    0x5F
#define IRQ_FIFO  (1u << 12)
#define IRQ_DONE  (1u << 13)

enum { M_LOW, M_UP, M_NUM, M_COUNT };

typedef struct {                      /* the 72 bytes on the air, little endian */
    uint16_t magic;
    uint8_t  flags, seq;
    uint32_t nonce;
    char     call[8];
    char     text[48];
    uint32_t mac;
    uint16_t crc, tail;
} pkt_t;
_Static_assert(sizeof(pkt_t) == 2u * PKT_WORDS, "the FSK packet is 72 bytes");

typedef struct { uint8_t magic, flags, mode, pad; uint32_t key[3]; } cfg_t;   /* 16 B */

static struct {
    uint8_t  head, count, scroll, inLen, rxLen, txLen, fsk;
    uint8_t  tapKey, tapIdx, raw, key, seq, tries, ackSeq, seenIdx;
    bool     tap, held, host, dirty, quit, saver, fn, keyEntry, txing, waiting, ackDue, cr, txOk;
    cfg_t    cfg;
    const app_api_t *A;
    char   (*hist)[COLS];
    pkt_t   *rxp, *out;                /* on app_main's stack                  */
    uint32_t now, tapT, keyT, drawT, ackT, ackAt;
    uint32_t k[4];                     /* the group key                        */
    uint16_t seen[4];                  /* (sender, seq) of the last messages   */
    char     call[8], ackCall[8];
    struct bufs *b;                    /* on app_main's stack                  */
} g;

struct bufs {
    char    in[IN_MAX + 1];            /* the keypad line                      */
    char    rx[IN_MAX + 1];            /* the computer's line                  */
    uint8_t tx[TX_MAX];                /* serial out                           */
};

