static char *T(char *b, uint16_t off) { g.A->asset_read(off, b, TEXT_MAX); return b; }
static uint8_t slen(const char *s) { uint8_t n = 0; while (s[n]) n++; return n; }
static bool due(uint32_t t) { return (int32_t)(g.now - t) >= 0; }

/* ---- serial out: buffered; txOk false when a write failed ---- */
static void flush(void) {
    if (g.txLen && !g.A->serial_write(APP_SERIAL_USB, g.b->tx, g.txLen)) g.txOk = false;
    g.txLen = 0;
}
static void outc(char c) { if (g.txLen >= TX_MAX) flush(); g.b->tx[g.txLen++] = (uint8_t)c; }
static void outs(const char *s) { while (*s) outc(*s++); }

/* ---- history ---- */
static void addRow(const char *s, uint8_t n) {
    char *r = g.hist[g.head];
    for (uint8_t i = 0; i < COLS; i++) r[i] = i < n ? s[i] : '\0';
    g.head = (uint8_t)((g.head + 1u) & (HROWS - 1u));
    if (g.count < HROWS) g.count++;
    g.scroll = 0;
    g.dirty = true;
}
/* A line on the screen (wrapped) and, with a host, to the computer. */
static void say(const char *s) {
    uint8_t n = slen(s);
    for (const char *p = s; n; ) { uint8_t k = n > COLS ? COLS : n; addRow(p, k); p += k; n = (uint8_t)(n - k); }
    if (g.host) { outs(s); outc('\r'); outc('\n'); flush(); }
}
static void sayT(uint16_t off) { char t[TEXT_MAX]; say(T(t, off)); }
static char *put(char *o, const char *s) { while (*s) *o++ = *s++; *o = '\0'; return o; }
static char *putT(char *o, uint16_t off) { char t[TEXT_MAX]; return put(o, T(t, off)); }

static void beep(uint16_t hz, uint16_t ms) { g.A->play_tone(hz, ms); }
static void notify(void) {
    g.A->backlight_on();
    if (!(g.cfg.flags & CF_MUTE)) beep(1200, 40);
}

/* ---- crypto: XTEA, a CBC-MAC tag, counter-mode text ---- */
static void xtea(uint32_t *v, const uint32_t *k) {
    uint32_t v0 = v[0], v1 = v[1], sum = 0;
    for (uint8_t i = 0; i < 32u; i++) {
        v0 += (((v1 << 4) ^ (v1 >> 5)) + v1) ^ (sum + k[sum & 3u]);
        sum += 0x9E3779B9u;
        v1 += (((v0 << 4) ^ (v0 >> 5)) + v0) ^ (sum + k[(sum >> 11) & 3u]);
    }
    v[0] = v0; v[1] = v1;
}
static void setKey(void) {                      /* cfg -> the 128-bit key */
    for (uint8_t i = 0; i < 3u; i++) g.k[i] = (g.cfg.flags & CF_KEY) ? g.cfg.key[i] : 0;
    g.k[3] = g.k[0] ^ g.k[1] ^ g.k[2];
}
static uint32_t mac(const pkt_t *p);
/* Passphrase -> 96 key bits: the tag of a packet holding the passphrase
 * (up to 48 characters) under a fixed key, three lanes. Only the result is
 * kept; nothing of it ever goes on the air. */
static void keyFrom(const char *p) {
    pkt_t *b = g.rxp;
    memset(b, 0, sizeof *b);
    for (uint8_t i = 0; i < 48u && p[i]; i++) b->text[i] = p[i];
    memset(g.k, 0, sizeof g.k);
    for (uint8_t l = 0; l < 3u; l++) { b->seq = l; g.cfg.key[l] = mac(b); }
    g.cfg.flags |= CF_KEY;
    setKey();
    sayT(T_KEYSET);
}
static uint32_t mac(const pkt_t *p) {           /* over bytes 0..63 */
    uint32_t v[2] = { 0, 0 }, k[4];
    for (uint8_t i = 0; i < 4u; i++) k[i] = g.k[i] ^ 0xA5A5A5A5u;
    const uint32_t *w = (const uint32_t *)p;
    for (uint8_t i = 0; i < 16u; i += 2u) { v[0] ^= w[i]; v[1] ^= w[i + 1]; xtea(v, k); }
    return v[0];
}
static void ctr(pkt_t *p) {                   /* the text, XOR keystream */
    uint32_t *t = (uint32_t *)p->text;
    for (uint8_t i = 0; i < 12u; i += 2u) {
        uint32_t v[2] = { p->nonce, ((uint32_t)p->seq << 8) | i };
        xtea(v, g.k);
        t[i] ^= v[0]; t[i + 1] ^= v[1];
    }
}
static uint16_t crc16(const void *buf, uint8_t n) {
    const uint8_t *d = buf;
    uint16_t c = 0;
    while (n--) {
        c ^= (uint16_t)(*d++ << 8);
        for (uint8_t b = 0; b < 8u; b++) c = (c & 0x8000u) ? (uint16_t)((c << 1) ^ 0x1021u) : (uint16_t)(c << 1);
    }
    return c;
}

/* ---- BK4819 FSK (BEAM) ---- */
static void bk_seq(uint16_t off, uint16_t len) {
    uint16_t s[SEQ_RX_LEN / 2u];
    g.A->asset_read(off, s, len);
    for (const uint16_t *w = s; w < s + len / 2u; w += 2) {
        if (w[0] == SEQ_DELAY) g.A->delay_ms(w[1]);
        else g.A->bk_write((uint8_t)w[0], w[1]);
    }
}
#define SEQ(name) bk_seq(name, name##_LEN)
static void rxStart(void) { g.fsk = 0; SEQ(SEQ_SETUP); SEQ(SEQ_RX); }
/* true once a packet with a good hardware CRC is in g.rxp */
static bool rxPoll(void) {
    const app_api_t *A = g.A;
    uint16_t *p = (uint16_t *)g.rxp;
    while (A->bk_read(REG_0C) & 1u) {
        A->bk_write(REG_02, 0);
        const uint16_t irq = A->bk_read(REG_02);
        if (irq & (IRQ_FIFO | IRQ_DONE)) {
            uint8_t n = (irq & IRQ_DONE) ? (uint8_t)(PKT_WORDS - g.fsk) : 4u;
            while (n--) {
                const uint16_t w = A->bk_read(REG_5F);
                if (g.fsk < PKT_WORDS) p[g.fsk++] = w;
            }
        }
    }
    if (g.fsk < PKT_WORDS) return false;
    const bool ok = !(A->bk_read(REG_0B) & 0x0010u);
    rxStart();
    return ok;
}
static void draw(void);
static bool transmit(const pkt_t *p) {
    const app_api_t *A = g.A;
    if (A->tx_state()) { sayT(T_TXNO); beep(300, 120); return false; }
    g.txing = true; draw();
    SEQ(SEQ_RESET);
    SEQ(SEQ_SETUP);
    A->tx_set_params();
    SEQ(SEQ_TX_LOAD);
    const uint16_t *w = (const uint16_t *)p;
    for (uint8_t i = 0; i < PKT_WORDS; i++) A->bk_write(REG_5F, w[i]);
    SEQ(SEQ_TX_GO);
    for (uint16_t t = PKT_WORDS * 3u + 100u; t && !(A->bk_read(REG_0C) & 1u); t--) A->delay_ms(5);
    SEQ(SEQ_TX_END);
    A->tx_end();
    rxStart();
    g.txing = false; g.dirty = true;
    return true;
}

/* ---- messages ---- */
static void build(pkt_t *p, uint8_t flags, const char *text, uint8_t n) {
    memset(p, 0, sizeof *p);
    p->magic = MAGIC; p->flags = flags; p->seq = g.seq; p->nonce = g.A->rand32();
    for (uint8_t i = 0; i < 8u; i++) p->call[i] = g.call[i];
    for (uint8_t i = 0; i < n; i++) p->text[i] = text[i];
    if (flags & P_ENC) ctr(p);
    p->mac = mac(p);
    p->crc = crc16(p, 68); p->tail = TAIL;
}
static bool sendText(const char *s, uint8_t n) {
    if (!n) return false;
    g.seq++;
    build(g.out, (g.cfg.flags & CF_ENC) ? P_ENC : 0, s, n);
    if (!transmit(g.out)) return false;
    char row[IN_MAX + 3];
    row[0] = '>'; row[1] = ' ';
    for (uint8_t i = 0; i < n; i++) row[2 + i] = s[i];
    row[2 + n] = '\0';
    say(row);
    g.waiting = true; g.tries = 1;
    g.ackT = g.now + ACK_MS + (g.A->rand32() & 511u);
    return true;
}
static bool sameCall(const char *a, const char *b) {
    for (uint8_t i = 0; i < 8u; i++) if (a[i] != b[i]) return false;
    return true;
}
static void onPacket(pkt_t *p) {
    if (p->magic != MAGIC || p->tail != TAIL || crc16(p, 68) != p->crc) return;
    if (sameCall(p->call, g.call)) return;
    p->call[7] = '\0';
    const bool ok = mac(p) == p->mac;
    char row[64], *o;
    if (p->flags & P_ACK) {                      /* "my message got there" */
        if (ok && g.waiting && sameCall(p->text, g.call) && (uint8_t)p->text[8] == g.out->seq) {
            g.waiting = false;
            put(putT(row, T_ACKED), p->call);
            say(row);
            beep(1800, 30);
        }
        return;
    }
    const uint16_t id = (uint16_t)(crc16(p->call, 8) ^ p->seq);
    bool dup = false;
    for (uint8_t i = 0; i < 4u; i++) dup |= g.seen[i] == id;
    if (ok) {                                    /* acknowledge, after a random pause */
        for (uint8_t i = 0; i < 8u; i++) g.ackCall[i] = p->call[i];
        g.ackSeq = p->seq; g.ackDue = true;
        g.ackAt = g.now + 150u + (g.A->rand32() & 511u);
    }
    if (dup) return;
    g.seen[g.seenIdx++ & 3u] = id;
    o = put(row, p->call);
    *o++ = !ok ? '?' : (p->flags & P_ENC) ? '*' : '>';
    *o++ = ' ';
    if ((p->flags & P_ENC) && !ok) put(o, "(cozulemedi)");
    else {
        if (p->flags & P_ENC) ctr(p);
        uint8_t i = 0;
        for (; i < 48u && p->text[i]; i++) o[i] = (p->text[i] >= ' ' && p->text[i] < 127) ? p->text[i] : '?';
        o[i] = '\0';
    }
    say(row);
    notify();
}
static void sendAck(void) {
    char t[9];
    for (uint8_t i = 0; i < 8u; i++) t[i] = g.ackCall[i];
    t[8] = (char)g.ackSeq;
    g.ackDue = false;
    build(g.rxp, P_ACK, t, 9);
    transmit(g.rxp);
}

/* ---- mode and settings ---- */
static uint8_t mode(void) { return !(g.cfg.flags & CF_KEY) ? 0u : (g.cfg.flags & CF_ENC) ? 2u : 1u; }
static void setEnc(bool on) {
    if (on && !(g.cfg.flags & CF_KEY)) { sayT(T_NEEDKEY); return; }
    g.cfg.flags = (uint8_t)(on ? g.cfg.flags | CF_ENC : g.cfg.flags & ~CF_ENC);
    if (on) sayT(T_WARN);
    sayT((uint16_t)(T_MODESET + mode() * T_MODESET_STRIDE));
}

/* ---- the computer's lines ---- */
static void lineIn(void) {
    g.b->rx[g.rxLen] = '\0';
    const char *s = g.b->rx;
    if (*s == '/') {                             /* /key <passphrase>, /echo off */
        if (s[1] == 'k' && g.rxLen > 5u) keyFrom(s + 5);
        else if (s[1] == 'e') sayT(T_ECHO);
        return;
    }
    sendText(s, g.rxLen);
}
/* The computer sends ASCII (rfkopru.py writes Turkish letters as c g i o s
 * u): any other UTF-8 character becomes one '?'. */
static void rxByte(uint8_t b) {
    if (b >= 0x80) {
        if (b < 0xC0) return;
        b = '?';
    }
    if (b == '\r' || b == '\n') {
        const bool lf = b == '\n' && g.cr;
        g.cr = b == '\r';
        if (!lf && g.rxLen) lineIn();
        g.rxLen = 0;
        return;
    }
    if (b == 8 || b == 127) { if (g.rxLen) g.rxLen--; return; }
    if (b < ' ') return;
    g.cr = false;
    if (g.rxLen < IN_MAX) g.b->rx[g.rxLen++] = (char)b;
}
static void usb(void) {
    const uint8_t st = g.A->serial_ctl(APP_SERIAL_USB, 0);
    const bool h = (st & APP_SERIAL_HOST) != 0;
    if (h != g.host) {
        g.host = h; g.dirty = true;
        if (h) { char s[48]; put(putT(s, T_BANNER), g.call); outs(s); outs("\r\n"); flush(); }
    }
    uint8_t buf[32];
    for (uint8_t rep = 0; rep < 8u; rep++) {
        const uint16_t n = g.A->serial_read(APP_SERIAL_USB, buf, sizeof buf);
        if (!n) break;
        for (uint16_t i = 0; i < n; i++) rxByte(buf[i]);
    }
}

/* ---- keypad ---- */
static char cased(char c) { return (g.cfg.mode == M_UP && c >= 'a' && c <= 'z') ? (char)(c - 32) : c; }
static void ins(char c) { if (g.inLen < IN_MAX) g.b->in[g.inLen++] = c; else beep(300, 120); }
static void typeKey(uint8_t k) {
    if (g.cfg.mode == M_NUM) { g.tap = false; ins((char)('0' + k)); return; }
    char m[KEYMAP_STRIDE];
    g.A->asset_read((uint16_t)(KEYMAP + k * KEYMAP_STRIDE), m, KEYMAP_STRIDE);
    if (g.tap && g.tapKey == k) {
        if (!m[++g.tapIdx]) g.tapIdx = 0;
        g.b->in[g.inLen - 1] = cased(m[g.tapIdx]);
    } else {
        const uint8_t n = g.inLen;
        ins(cased(m[0]));
        if (g.inLen == n) return;
        g.tap = true; g.tapKey = k; g.tapIdx = 0;
    }
    g.tapT = g.now;
}
static uint8_t maxScroll(void) {
    const uint8_t max = g.count > VROWS ? (uint8_t)(g.count - VROWS) : 0;
    if (g.scroll > max) g.scroll = max;
    return max;
}
static void onPress(uint8_t k) {
    g.dirty = true;
    if (g.fn) {                                  /* F + key */
        g.fn = false;
        if (k == APP_KEY_1) setEnc(!(g.cfg.flags & CF_ENC));
        else if (k == APP_KEY_2) { g.keyEntry = true; sayT(T_KEYASK); }
        else if (k == APP_KEY_3) {
            g.cfg.flags ^= CF_MUTE;
            sayT((uint16_t)(T_SOUND + !(g.cfg.flags & CF_MUTE) * T_SOUND_STRIDE));
        }
        return;
    }
    if (k <= APP_KEY_9) { typeKey(k); return; }
    g.tap = false;
    switch (k) {
    case APP_KEY_MENU:
        g.b->in[g.inLen] = '\0';
        if (g.keyEntry) { g.keyEntry = false; if (g.inLen) keyFrom(g.b->in); g.inLen = 0; }
        else if (sendText(g.b->in, g.inLen)) g.inLen = 0;     /* kept when TX is refused */
        break;
    case APP_KEY_EXIT: if (g.inLen) g.inLen--; else if (g.keyEntry) g.keyEntry = false; else g.quit = true; break;
    case APP_KEY_STAR: if (++g.cfg.mode >= M_COUNT) g.cfg.mode = M_LOW; break;
    case APP_KEY_F:    g.fn = true; break;
    case APP_KEY_UP:   if (g.scroll < maxScroll()) g.scroll++; break;
    case APP_KEY_DOWN: if (g.scroll) g.scroll--; break;
    default: break;
    }
}
static void keys(void) {
    const uint8_t k = g.A->get_key();
    if (k == APP_KEY_SAVER) { g.saver = true; return; }
    g.saver = false;
    if (k == APP_KEY_WAKE) { g.dirty = true; g.raw = g.key = APP_KEY_INVALID; return; }
    if (k != g.raw) { g.raw = k; return; }
    if (k == g.key) {
        if (k == APP_KEY_INVALID) return;
        if (!g.held) {
            if (g.now - g.keyT >= LONG_MS) {
                g.held = true;
                if (k <= APP_KEY_9 && g.tap && g.tapKey == k) { g.b->in[g.inLen - 1] = (char)('0' + k); g.tap = false; g.dirty = true; }
                else if (k == APP_KEY_EXIT) { g.inLen = 0; g.dirty = true; }
            }
        }
        return;
    }
    g.key = k; g.held = false; g.keyT = g.now;
    if (k != APP_KEY_INVALID) onPress(k);
}

/* ---- screen: USB Term 2.0's layout ---- */
static void capsule(const char *t, uint8_t x) {
    g.A->print_inverse(t, x, 0, true, true, (uint8_t)(x + 4u * slen(t)));
}
static void draw(void) {
    const app_api_t *A = g.A;
    char t[TEXT_MAX], s[COLS + 1];
    A->display_clear();
    A->status_clear();
    capsule(T(t, T_TITLE), 2);
    capsule(T(t, (uint16_t)(T_MODE + mode() * T_MODE_STRIDE)), 40);
    if (g.txing) capsule(T(t, T_TX), 70);
    else if (g.fn) capsule(T(t, T_F), 70);
    else A->print_tiny(T(t, (uint16_t)(T_MODES + g.cfg.mode * T_MODES_STRIDE)), 70, 1, true, true);
    A->draw_battery();

    const uint8_t base = (uint8_t)(maxScroll() - g.scroll);
    for (uint8_t r = 0; r < VROWS && base + r < g.count; r++) {
        const char *src = g.hist[(g.head - g.count + base + r) & (HROWS - 1u)];
        uint8_t j = 0;
        for (; j < COLS && src[j]; j++) s[j] = src[j];
        s[j] = '\0';
        A->print_tiny(s, 0, (uint8_t)(r * 6u), false, true);
    }
    for (uint8_t x = 0; x < 128u; x++) A->fb[4][x] |= 0x20u;     /* rule, y 37 */
    const uint8_t cur = (uint8_t)(g.inLen - (g.tap ? 1u : 0u));
    uint8_t first = 0;
    while (cur >= first + 2u * IN_COLS) first = (uint8_t)(first + IN_COLS);
    for (uint8_t l = 0; l < 2u; l++) {
        const uint8_t a = (uint8_t)(first + l * IN_COLS);
        uint8_t j = 0;
        for (; j < IN_COLS && a + j < g.inLen; j++) s[j] = g.b->in[a + j];
        s[j] = '\0';
        A->print_normal(s, 0, 0, (uint8_t)(IN_LINE + l));
    }
    uint8_t c = (uint8_t)(cur - first), line = IN_LINE;
    if (c >= IN_COLS) { c = (uint8_t)(c - IN_COLS); line++; }
    uint8_t *p = A->fb[line] + c * 7u;
    for (uint8_t i = 0; i < 7u; i++) p[i] ^= 0x7Fu;
    A->blit_status();
    A->blit_full();
}

__attribute__((section(".text.entry"), used))
void app_main(const app_api_t *api) {
    char hist[HROWS][COLS];
    pkt_t rx, out;                      /* on the stack: the overlay holds the code */
    struct bufs b;
    g.A = api; g.hist = hist; g.rxp = &rx; g.out = &out; g.b = &b;
    g.raw = g.key = APP_KEY_INVALID;
    api->cfg_load((uint8_t *)&g.cfg, sizeof g.cfg);
    if (g.cfg.magic != CFG_MAGIC || g.cfg.mode >= M_COUNT) {
        memset(&g.cfg, 0, sizeof g.cfg);
        g.cfg.magic = CFG_MAGIC;
    }
    setKey();
    api->boot_callsign(g.call, sizeof g.call);
    if (!g.call[0]) { put(g.call, "NOCALL"); sayT(T_NOCALL); }
    g.seq = (uint8_t)api->rand32();
    api->backlight_on();
    { char s[32]; put(putT(s, T_INFO), g.call); say(s); }
    sayT(T_HELLO);
    rxStart();
    g.dirty = true;
    while (!g.quit) {
        g.now = api->ticks_ms();
        usb();
        if (rxPoll()) onPacket(&rx);
        keys();
        if (g.ackDue && due(g.ackAt)) sendAck();
        if (g.waiting && due(g.ackT)) {
            if (g.tries++ < TRIES) { transmit(&out); g.ackT = g.now + ACK_MS + (api->rand32() & 511u); }
            else { g.waiting = false; sayT(T_FAIL); beep(300, 120); }
        }
        if (g.tap && g.now - g.tapT >= TAP_MS) { g.tap = false; g.dirty = true; }
        if (g.now - g.drawT >= REDRAW_MS) { api->battery_sample(); g.dirty = true; }
        api->backlight_update();
        if (g.dirty && !g.saver) { g.dirty = false; g.drawT = g.now; draw(); }
        api->delay_ms(POLL_MS);
    }
    SEQ(SEQ_RESET);
    api->cfg_save((const uint8_t *)&g.cfg, sizeof g.cfg);
}
