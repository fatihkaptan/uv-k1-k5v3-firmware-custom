/*
 * BK Lab - the BK4819 / BK4829 RF chip's registers, live, for a developer.
 * API level 3. See README.md.
 *
 * List: registers 0x00-0x7F, six on screen, read live (status and meter
 * registers move), named where the firmware's driver makes their use clear;
 * '*' marks a register written in this session. RSSI (half dB), noise and
 * glitch at the bottom. UP / DOWN (held: fast), 0-7 jump to 0x00 .. 0x70.
 *
 * MENU: the bit editor: the value large, its 16 bits, a cursor (UP / DOWN),
 * MENU flips the bit in an edit buffer, F writes it to the chip, '*' takes
 * the chip's value back. 0x30, 0x33 and 0x36 can key the transmitter (RX/TX
 * enables, the PA switch on a GPIO, the PA): they need F twice.
 *
 * Every register written is restored to the value read at launch when the
 * app exits (then the loader sets the radio up again anyway).
 *
 * USB, one command per line, registers and values in hex: "r 13 [n]",
 * "w 13 03DF", "w! 30 BFF1" (a protected one), "d" (all), "m 67 [ms]"
 * (stream every ms, decimal, 100 by default, until any byte),
 * "s" (RSSI, noise, glitch), "geri" (restore now). tools/bklab/bklab.py is
 * a shell and a Python API over it.
 */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../app_api.h"
#include "bklab_assets.h"     /* generated by gen_assets.py */

#define NREG      0x80u
#define ROWS      6u
#define POLL_MS   10u
#define LIVE_MS   200u
#define LONG_MS   500u
#define REP_MS    60u
#define BAT_MS    5000u
#define REG_63    0x63      /* glitch */
#define REG_65    0x65      /* noise  */
#define REG_67    0x67      /* RSSI, half dB */
#define CFG_MAGIC 0x42u

enum { V_LIST, V_BITS };

typedef struct { uint8_t magic, sel, pad[2]; } cfg_t;

static struct {
    uint8_t  view, sel, top, cur, raw, key, rxLen, mon, armed;
    bool     held, dirty, quit, saver, host;
    cfg_t    cfg;
    const app_api_t *A;
    uint16_t *orig;                    /* NREG values read at launch (stack)   */
    uint16_t edit;                     /* the bit editor's buffer              */
    uint8_t  written[NREG / 8u];       /* registers written: restore at exit   */
    uint32_t now, keyT, repT, liveT, batT, monT, monMs;
    char     rx[24];
} g;

#ifndef HOST_TEST
void *memset(void *d, int c, size_t n) { uint8_t *p = d; while (n) p[--n] = (uint8_t)c; return d; }
void *memcpy(void *d, const void *s, size_t n) {
    uint8_t *p = d; const uint8_t *q = s; while (n) { --n; p[n] = q[n]; } return d;
}
uint64_t __aeabi_uidivmod(uint32_t n, uint32_t d) { return g.A->uidivmod(n, d); }
uint64_t __aeabi_uidiv(uint32_t n, uint32_t d) __attribute__((alias("__aeabi_uidivmod")));
#endif

static char *T(char *b, uint16_t off) { g.A->asset_read(off, b, TEXT_MAX); return b; }
static char *put(char *o, const char *s) { while (*s) *o++ = *s++; *o = '\0'; return o; }
static char *putT(char *o, uint16_t off) { char t[TEXT_MAX]; return put(o, T(t, off)); }
static char *putu(char *o, uint32_t u) { o = g.A->append_u32(o, u); *o = '\0'; return o; }
static uint8_t slen(const char *s) { uint8_t n = 0; while (s[n]) n++; return n; }
static char *hex(char *o, uint32_t v, uint8_t digits) {
    while (digits--) { const uint8_t d = (uint8_t)((v >> (4u * digits)) & 15u); *o++ = (char)(d < 10u ? '0' + d : 'A' - 10 + d); }
    *o = '\0';
    return o;
}
static char *name(char *o, uint8_t r) { return putT(o, (uint16_t)(NAMES + r * NAMES_STRIDE)); }
static bool prot(uint8_t r) {
    uint8_t p[PROT_LEN];
    g.A->asset_read(PROT, p, PROT_LEN);
    for (uint8_t i = 0; i < PROT_LEN; i++) if (p[i] == r) return true;
    return false;
}
static uint16_t rd(uint8_t r) { return g.A->bk_read(r); }
static void wr(uint8_t r, uint16_t v) {
    g.A->bk_write(r, v);
    g.written[r >> 3] |= (uint8_t)(1u << (r & 7u));
    g.dirty = true;
}
static bool isWritten(uint8_t r) { return (g.written[r >> 3] >> (r & 7u)) & 1u; }
static uint8_t restore(void) {                  /* the launch values, last written last */
    uint8_t n = 0;
    for (uint8_t r = NREG; r--; )
        if (isWritten(r)) { g.A->bk_write(r, g.orig[r]); n++; }
    memset(g.written, 0, sizeof g.written);
    g.dirty = true;
    return n;
}
/* "RSSI -97.5  Gr 12  Gl 3" */
static char *meters(char *o) {
    const uint16_t q = rd(REG_67) & 0x1FFu;           /* dBm = q / 2 - 160 */
    o = put(o, "RSSI ");
    if (q < 320u) { *o++ = '-'; o = putu(o, (320u - q) >> 1); *o++ = '.'; *o++ = (q & 1u) ? '5' : '0'; }
    else { o = putu(o, (q - 320u) >> 1); *o++ = '.'; *o++ = (q & 1u) ? '5' : '0'; }
    o = putu(put(o, "  Gr "), rd(REG_65) & 0x7Fu);
    return putu(put(o, "  Gl "), rd(REG_63) & 0xFFu);
}

/* ---- USB ---- */
static void out(const char *s) {
    if (!g.host) return;
    g.A->serial_write(APP_SERIAL_USB, s, slen(s));
    g.A->serial_write(APP_SERIAL_USB, "\r\n", 2);
}
static void outReg(uint8_t r) { char s[12], *o = hex(s, r, 2); *o++ = '='; hex(o, rd(r), 4); out(s); }
static const char *hexIn(const char *s, uint32_t *v) {   /* skips spaces; NULL: no digits */
    while (*s == ' ') s++;
    uint32_t x = 0;
    const char *p = s;
    for (;; p++) {
        const char c = (char)(*p | 0x20);
        if (c >= '0' && c <= '9') x = (x << 4) | (uint32_t)(c - '0');
        else if (c >= 'a' && c <= 'f') x = (x << 4) | (uint32_t)(c - 'a' + 10);
        else break;
    }
    *v = x;
    return p == s ? NULL : p;
}
static void lineIn(void) {
    char *s = g.rx, t[TEXT_MAX];
    uint32_t r, v, n = 1;
    s[g.rxLen] = '\0';
    const char c = (char)(s[0] | 0x20);
    if (s[0] == '/') { out(T(t, T_ECHO)); return; }
    if (c == 'g') { char o[32]; putu(putT(o, T_GERI), restore()); out(o); return; }
    if (c == 's') { char o[40]; meters(o); out(o); return; }
    if (c == 'd') {                                  /* 16 lines of 8 */
        for (uint8_t a = 0; a < NREG; a += 8u) {
            char o[48], *p = hex(o, a, 2);
            *p++ = ':';
            for (uint8_t i = 0; i < 8u; i++) { *p++ = ' '; p = hex(p, rd((uint8_t)(a + i)), 4); }
            out(o);
        }
        return;
    }
    const bool force = s[1] == '!';
    const char *p = hexIn(s + 1 + force, &r);
    if (!p || r >= NREG) { out(T(t, T_BAD)); return; }
    if (c == 'r') {
        if (hexIn(p, &n) == NULL || !n) n = 1;
        for (uint32_t i = 0; i < n && r + i < NREG; i++) outReg((uint8_t)(r + i));
    } else if (c == 'w' && hexIn(p, &v)) {
        if (prot((uint8_t)r) && !force) { out(T(t, T_PROT)); return; }
        wr((uint8_t)r, (uint16_t)v);
        outReg((uint8_t)r);
    } else if (c == 'm') {                          /* "m 67 250": every 250 ms (decimal) */
        v = 0;
        while (*p == ' ') p++;
        while (*p >= '0' && *p <= '9') v = v * 10u + (uint32_t)(*p++ - '0');
        g.mon = (uint8_t)(r | 0x80u);
        g.monMs = v >= 20u ? v : 100u;
        g.monT = g.now;
    } else out(T(t, T_BAD));
}
static void usb(void) {
    const app_api_t *A = g.A;
    const bool h = (A->serial_ctl(APP_SERIAL_USB, 0) & APP_SERIAL_HOST) != 0;
    if (h != g.host) { g.host = h; g.dirty = true; if (h) { char t[TEXT_MAX]; out(T(t, T_BANNER)); } }
    uint8_t buf[32];
    uint16_t n;
    while ((n = A->serial_read(APP_SERIAL_USB, buf, sizeof buf)) != 0)
        for (uint16_t i = 0; i < n; i++) {
            const char c = (char)buf[i];
            if (c == '\r' || c == '\n') { if (g.rxLen) lineIn(); g.rxLen = 0; continue; }
            g.mon = 0;                               /* any other byte ends a monitor */
            if (g.rxLen < sizeof g.rx - 1u) g.rx[g.rxLen++] = c;
        }
    if (g.mon && g.now - g.monT >= g.monMs) { g.monT = g.now; outReg((uint8_t)(g.mon & 0x7Fu)); }
}

/* ---- keys ---- */
static void move(int8_t d) {
    g.sel = (uint8_t)((g.sel + NREG + d) % NREG);
    if (g.sel < g.top) g.top = g.sel;
    if (g.sel >= g.top + ROWS) g.top = (uint8_t)(g.sel - ROWS + 1u);
    if (g.top > NREG - ROWS) g.top = NREG - ROWS;
}
static void onPress(uint8_t k) {
    g.dirty = true;
    if (g.view == V_LIST) {
        if (k <= APP_KEY_7) { g.sel = (uint8_t)(k << 4); g.top = g.sel > NREG - ROWS ? NREG - ROWS : g.sel; }
        else if (k == APP_KEY_UP) move(-1);
        else if (k == APP_KEY_DOWN) move(1);
        else if (k == APP_KEY_MENU) { g.view = V_BITS; g.edit = rd(g.sel); g.cur = 0; g.armed = 0; }
        else if (k == APP_KEY_EXIT) g.quit = true;
        return;
    }
    const bool fkey = k == APP_KEY_F;
    if (!fkey) g.armed = 0;
    switch (k) {
    case APP_KEY_UP:   g.cur = (uint8_t)((g.cur + 15u) & 15u); break;
    case APP_KEY_DOWN: g.cur = (uint8_t)((g.cur + 1u) & 15u); break;
    case APP_KEY_MENU: g.edit ^= (uint16_t)(0x8000u >> g.cur); break;
    case APP_KEY_STAR: g.edit = rd(g.sel); break;
    case APP_KEY_F:
        if (prot(g.sel) && !g.armed) { g.armed = 1; g.A->play_tone(600, 80); break; }
        g.armed = 0;
        wr(g.sel, g.edit);
        g.A->play_tone(1500, 40);
        break;
    case APP_KEY_EXIT: g.view = V_LIST; break;
    default: break;
    }
}
static void keys(void) {
    const uint8_t k = g.A->get_key();
    if (k == APP_KEY_SAVER) { g.saver = true; return; }
    g.saver = false;
    if (k == APP_KEY_WAKE) { g.dirty = true; g.raw = g.key = APP_KEY_INVALID; return; }
    if (k != g.raw) { g.raw = k; return; }
    if (k == g.key) {                                 /* held: UP / DOWN repeat */
        if ((k == APP_KEY_UP || k == APP_KEY_DOWN) && g.now - g.keyT >= LONG_MS && g.now - g.repT >= REP_MS) {
            g.repT = g.now; onPress(k);
        }
        return;
    }
    g.key = k; g.keyT = g.now;
    if (k != APP_KEY_INVALID) onPress(k);
}

/* ---- screen ---- */
static void draw(void) {
    const app_api_t *A = g.A;
    char s[40], *o;
    A->display_clear();
    A->status_clear();
    T(s, T_TITLE);
    A->print_inverse(s, 2, 0, true, true, (uint8_t)(2u + 4u * slen(s)));
    if (g.host) { T(s, T_USB); A->print_inverse(s, 34, 0, true, true, (uint8_t)(34u + 4u * slen(s))); }
    A->draw_battery();
    if (g.view == V_LIST) {
        for (uint8_t r = 0; r < ROWS; r++) {
            const uint8_t reg = (uint8_t)(g.top + r);
            o = hex(s, reg, 2);
            *o++ = isWritten(reg) ? '*' : ' ';
            o = hex(o, rd(reg), 4);
            *o++ = ' ';
            name(o, reg);
            A->print_normal(s, 0, 0, r);
            if (reg == g.sel) for (uint8_t x = 0; x < 128u; x++) A->fb[r][x] ^= 0xFFu;
        }
        meters(s);
        A->print_tiny(s, 0, 50, false, true);
    } else {
        o = hex(s, g.sel, 2); *o++ = ' ';
        name(o, g.sel);
        A->print_normal(s, 0, 0, 0);
        hex(s, g.edit, 4);
        A->print_string(s, 0, 127, 1, 12);                  /* big, lines 1-2 */
        for (uint8_t i = 0; i < 16u; i++) {                  /* bits 15..8 on line 3, 7..0 on 4 */
            const char b[2] = { (char)('0' + ((g.edit >> (15u - i)) & 1u)), 0 };
            const uint8_t line = (uint8_t)(3u + (i >> 3)), x = (uint8_t)(16u * (i & 7u));
            A->print_normal(b, (uint8_t)(x + 3u), 0, line);
            if (i == g.cur) for (uint8_t j = 1; j < 15u; j++) A->fb[line][x + j] ^= 0xFFu;
        }
        o = putu(putT(s, T_BIT), 15u - g.cur);
        hex(putT(o, T_CIP), rd(g.sel), 4);
        A->print_tiny(s, 0, 42, false, true);
        A->print_tiny(T(s, g.armed ? T_ARM : T_BITHINT), 0, 50, false, true);
    }
    A->blit_status();
    A->blit_full();
}

__attribute__((section(".text.entry"), used))
void app_main(const app_api_t *api) {
    uint16_t orig[NREG];                /* on the stack: the overlay holds the code */
    g.A = api; g.orig = orig;
    g.raw = g.key = APP_KEY_INVALID;
    for (uint8_t r = 0; r < NREG; r++) orig[r] = api->bk_read(r);
    api->cfg_load((uint8_t *)&g.cfg, sizeof g.cfg);
    if (g.cfg.magic == CFG_MAGIC && g.cfg.sel < NREG) { g.sel = g.cfg.sel; move(0); }
    api->backlight_on();
    g.dirty = true;
    while (!g.quit) {
        g.now = api->ticks_ms();
        usb();
        keys();
        if (g.now - g.liveT >= LIVE_MS) { g.liveT = g.now; g.dirty = true; }   /* live values */
        if (g.now - g.batT >= BAT_MS) { g.batT = g.now; api->battery_sample(); }
        api->backlight_update();
        if (g.dirty && !g.saver) { g.dirty = false; draw(); }
        api->delay_ms(POLL_MS);
    }
    restore();
    g.cfg.magic = CFG_MAGIC; g.cfg.sel = g.sel;
    api->cfg_save((const uint8_t *)&g.cfg, sizeof g.cfg);
}
