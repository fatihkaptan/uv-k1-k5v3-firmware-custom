/*
 * Mors Okur - decodes Morse heard by the radio's own microphone: a whistle,
 * a practice oscillator, a computer or another radio's speaker. API level 3,
 * receive only. See README.md.
 *
 * The microphone reaches nothing but the BK4819's mic ADC. The app switches
 * that ADC and the TX DSP on with the PLL, the VCO and the PA left off (no RF
 * can come out) and reads the voice amplitude the DSP measures (REG_64, the
 * level the firmware's mic bar and VOX use): an envelope, whatever the pitch.
 *   - a median of three readings drops single spikes;
 *   - the readings under the threshold between marks are the quiet: its
 *     level and spread (the mean distance from it) follow the room (a louder
 *     room shows as a steady sound, below); the peak is the loudest mark,
 *     decaying in silence. A mark starts at the midpoint between the quiet
 *     level and the peak, but never closer to the quiet level than the
 *     margin: (14 - sensitivity) / 2 spreads, or (10 - sensitivity) / 16 of
 *     the quiet level; it ends halfway back (hysteresis); DEB_N equal
 *     decisions make an edge;
 *   - the speed is set by hand (UP/DOWN, 5-40 WPM): a dot lasts 1200 / WPM
 *     ms, a mark longer than two dots is a dash. In the automatic mode (F)
 *     the boundary is midway between the shortest and the longest of the
 *     last NHIST marks when both kinds are there, else two dots, and the dot
 *     length follows every mark (most of the way at once when it is more
 *     than twice off);
 *   - 2 dots of silence end a letter (midway between 1 and 3), 5 a word
 *     (midway between 3 and 7).
 * A mark longer than MARK_MAX is a steady sound, not Morse: the quiet level
 * jumps to it. Source "R" (key 0) keeps the receiver on and adds the mic ADC
 * and the VOX detector instead, in case the first one reads nothing.
 * Decoded text also goes out on USB.
 */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../app_api.h"
#include "morsokur_assets.h"     /* generated by gen_assets.py */

#ifndef TRACE
#define TRACE(...)                   /* the host test prints the decisions */
#endif

#define REG_30     0x30
#define REG_31     0x31
#define REG_64     0x64
#define MIC_DSP    0x0306u   /* AF DAC, discriminator, mic ADC, TX DSP: PLL, VCO, PA off */
#define MIC_RX     0xBFF5u   /* the receiver as set up (0xBFF1) plus the mic ADC */
#define VOX_ON     0x0004u   /* REG_31 bit 2: the VOX detector */
#define POLL_MS    2u
#define DEB_N      3u        /* equal decisions for an edge */
#define WPM_MIN    5u
#define WPM_MAX    40u
#define DOT_MIN    24u       /* automatic mode: 50 WPM */
#define DOT_MAX    300u      /* 4 WPM */
#define GLITCH_MS  12u
#define MARK_MAX   2000u
#define NHIST      8u
#define DRAW_MS    150u
#define BAT_MS     5000u
#define COLS       18u
#define ROWS       5u
#define BAR_W      100u
#define CFG_MAGIC  0x50u
#define SENS_MAX   9u

typedef struct { uint8_t magic, sens, mode, wpm, oto; } cfg_t;

static struct {
    const app_api_t *A;
    cfg_t    cfg;
    bool     down, quit, dirty, saver, host;
    uint8_t  raw, key, cnt, depth, code, col, sp, mi, hi, rxLen;
    uint16_t lvl, on, peak, dot, reg31, med[3], hist[NHIST];
    uint32_t floorQ, devQ, now, edge, candAt, drawT, batT;  /* quiet level, its spread: x 16 */
    char     rows[ROWS][COLS + 1u];
    char     pat[8];
    char     rx[6];
} g;

#ifndef HOST_TEST
void *memset(void *d, int c, size_t n) { uint8_t *p = d; while (n) p[--n] = (uint8_t)c; return d; }
void *memcpy(void *d, const void *s, size_t n) {
    uint8_t *p = d; const uint8_t *q = s; while (n) { --n; p[n] = q[n]; } return d;
}
uint64_t __aeabi_uidivmod(uint32_t n, uint32_t d) { return g.A->uidivmod(n, d); }
uint64_t __aeabi_uidiv(uint32_t n, uint32_t d) __attribute__((alias("__aeabi_uidivmod")));
#endif

static char *T(char *b, uint16_t off) { g.A->asset_read(off, b, TEXT_MAX); return b; }
static char *put(char *o, const char *s) { while (*s) *o++ = *s++; *o = '\0'; return o; }
static char *putu(char *o, uint32_t u) { o = g.A->append_u32(o, u); *o = '\0'; return o; }
static uint8_t slen(const char *s) { uint8_t n = 0; while (s[n]) n++; return n; }

/* ---- USB: the decoded text, "/echo off" answered ---- */
static void send(const char *s, uint8_t n) { if (g.host) g.A->serial_write(APP_SERIAL_USB, s, n); }
static void sendT(uint16_t off) {                /* T() first: argument order is unspecified */
    char t[TEXT_MAX];
    T(t, off);
    send(t, slen(t));
    send("\r\n", 2);
}
static void usb(void) {
    const app_api_t *A = g.A;
    const bool h = (A->serial_ctl(APP_SERIAL_USB, 0) & APP_SERIAL_HOST) != 0;
    if (h != g.host) { g.host = h; if (h) sendT(T_BANNER); }
    uint8_t b[16];
    uint16_t n;
    while ((n = A->serial_read(APP_SERIAL_USB, b, sizeof b)) != 0)
        for (uint16_t i = 0; i < n; i++) {
            if (b[i] == '\r' || b[i] == '\n') {
                if (g.rxLen > 1u && g.rx[0] == '/' && g.rx[1] == 'e') sendT(T_ECHO);
                g.rxLen = 0;
            } else if (g.rxLen < sizeof g.rx) g.rx[g.rxLen++] = (char)b[i];
        }
}

/* ---- the microphone: its ADC on, no RF ---- */
static void mic(void) {
    const app_api_t *A = g.A;
    A->set_af(APP_AF_MUTE);
    A->bk_write(REG_30, 0);
    A->bk_write(REG_30, g.cfg.mode ? MIC_RX : MIC_DSP);
    A->bk_write(REG_31, g.cfg.mode ? (uint16_t)(g.reg31 | VOX_ON) : g.reg31);
}

/* ---- text: five rows, the last one being written ---- */
static void out(char c) {
    if (g.col >= COLS) {
        for (uint8_t r = 0; r + 1u < ROWS; r++) memcpy(g.rows[r], g.rows[r + 1u], COLS + 1u);
        memset(g.rows[ROWS - 1u], 0, COLS + 1u);
        g.col = 0;
        if (c == ' ') return;
    }
    g.rows[ROWS - 1u][g.col++] = c;
    send(&c, 1);
    g.dirty = true;
}
static void clearSym(void) { g.depth = 0; g.code = 1; g.pat[0] = '\0'; }
static void finish(void) {                      /* a letter's gap: the pattern -> a character */
    char c = '_';
    if (g.depth <= 6u) g.A->asset_read((uint16_t)(MORSE + g.code), &c, 1);
    TRACE("CHAR %s %c gap=%u\n", g.pat, c, (unsigned)(g.now - g.edge));
    out(c);
    clearSym();
    g.sp = 1;
}
static void mark(uint16_t d) {
    if (d < GLITCH_MS) return;
    if (d > MARK_MAX) { clearSym(); return; }
    g.hist[g.hi] = d;
    g.hi = (uint8_t)((g.hi + 1u) % NHIST);
    uint16_t mn = 0xFFFFu, mx = 0, b = (uint16_t)(2u * g.dot);
    for (uint8_t i = 0; i < NHIST; i++) {
        const uint16_t h = g.hist[i];
        if (!h) continue;
        if (h < mn) mn = h;
        if (h > mx) mx = h;
    }
    if (g.cfg.oto && mx >= 2u * mn) b = (uint16_t)((mn + mx) / 2u);   /* dots and dashes both seen */
    const bool dash = d > b;
    TRACE("MARK %u %c b=%u dot=%u\n", d, dash ? '-' : '.', b, g.dot);
    if (g.cfg.oto) {
        const uint32_t e = dash ? d / 3u : d;
        /* far off (a new speed): three quarters of the way at once, else a quarter */
        uint32_t dot = e > 2u * g.dot || 2u * e < g.dot ? (g.dot + 3u * e + 2u) / 4u : (3u * g.dot + e + 2u) / 4u;
        g.dot = (uint16_t)(dot < DOT_MIN ? DOT_MIN : dot > DOT_MAX ? DOT_MAX : dot);
    }
    if (g.depth < 7u) {
        g.pat[g.depth++] = dash ? '-' : '.';
        g.pat[g.depth] = '\0';
        g.code = (uint8_t)(g.code << 1 | dash);
    }
}
static void edge(bool down, uint32_t t) {
    if (!down) mark((uint16_t)(t - g.edge));
    g.down = down;
    g.edge = t;
    g.A->led(down);
    g.dirty = true;
}

/* ---- the envelope ---- */
static void sample(void) {
    g.med[g.mi] = g.A->bk_read(REG_64) & 0x7FFFu;
    g.mi = (uint8_t)((g.mi + 1u) % 3u);
    const uint16_t a = g.med[0], b = g.med[1], c = g.med[2];
    g.lvl = a > b ? (b > c ? b : a > c ? c : a) : (a > c ? a : b > c ? c : b);
    const uint32_t v = (uint32_t)g.lvl << 4;
    const uint16_t fl = (uint16_t)(g.floorQ >> 4);
    uint16_t m = (uint16_t)((g.devQ >> 4) * (14u - g.cfg.sens) / 2u);
    const uint16_t rel = (uint16_t)((uint32_t)fl * (10u - g.cfg.sens) >> 4);
    if (m < rel) m = rel;
    if (m < 8u) m = 8u;
    const uint16_t half = g.peak > fl ? (uint16_t)((g.peak - fl) >> 1) : 0;
    g.on = (uint16_t)(fl + (half > m ? half : m));
    const bool raw = g.lvl > (g.down ? (uint16_t)(fl + ((g.on - fl) >> 1)) : g.on);
    if (g.down) {
        if (g.lvl > g.peak) g.peak = g.lvl;
        if (g.now - g.edge > MARK_MAX) {        /* a steady sound: it is the quiet now */
            g.floorQ = v; g.peak = g.lvl; g.cnt = 0;
            edge(false, g.now);
            return;
        }
    } else if (!raw) {                          /* quiet: level and spread follow, the peak decays */
        const uint32_t d = v > g.floorQ ? v - g.floorQ : g.floorQ - v;
        if (d > g.devQ) g.devQ += (d - g.devQ) >> 6; else g.devQ -= (g.devQ - d) >> 6;
        if (v > g.floorQ) g.floorQ += (v - g.floorQ) >> 6; else g.floorQ -= (g.floorQ - v) >> 5;
        if (g.peak > fl) g.peak = (uint16_t)(g.peak - ((g.peak - fl) >> 9) - 1u);
    }
    if (raw == g.down) { g.cnt = 0; return; }
    if (!g.cnt++) g.candAt = g.now;
    if (g.cnt >= DEB_N) { g.cnt = 0; edge(raw, g.candAt); }
}
static void gaps(void) {
    if (g.down) return;
    const uint32_t gap = g.now - g.edge;
    if (g.depth && gap >= 2u * g.dot) finish();
    if (g.sp == 1u && gap >= 5u * g.dot) { out(' '); g.sp = 2; }
    if (g.sp == 2u && gap >= 20u * g.dot) { send("\r\n", 2); g.sp = 3; }
}

/* ---- keys ---- */
static void setSpeed(void) { g.dot = (uint16_t)(1200u / g.cfg.wpm); memset(g.hist, 0, sizeof g.hist); }
static void onPress(uint8_t k) {
    g.dirty = true;
    if (k >= APP_KEY_1 && k <= APP_KEY_9) { g.cfg.sens = k; return; }   /* APP_KEY_n == n */
    switch (k) {
    case APP_KEY_UP:   if (g.cfg.wpm < WPM_MAX) g.cfg.wpm++; setSpeed(); break;
    case APP_KEY_DOWN: if (g.cfg.wpm > WPM_MIN) g.cfg.wpm--; setSpeed(); break;
    case APP_KEY_F:    g.cfg.oto ^= 1u; setSpeed(); break;
    case APP_KEY_MENU:                          /* clear the text */
        memset(g.rows, 0, sizeof g.rows); g.col = 0; clearSym(); send("\r\n", 2);
        break;
    case APP_KEY_0:    g.cfg.mode ^= 1u; mic(); break;
    case APP_KEY_EXIT: g.quit = true; break;
    default: break;
    }
}
static void keys(void) {
    const uint8_t k = g.A->get_key();
    if (k == APP_KEY_SAVER) { g.saver = true; return; }
    g.saver = false;
    if (k == APP_KEY_WAKE) { g.dirty = true; g.raw = g.key = APP_KEY_INVALID; return; }
    if (k != g.raw) { g.raw = k; return; }      /* debounce: two equal readings */
    if (k == g.key) return;
    g.key = k;
    if (k != APP_KEY_INVALID) onPress(k);
}

/* ---- screen ---- */
static void fill(uint8_t x0, uint8_t x1, uint8_t y0, uint8_t y1) {
    for (uint8_t x = x0; x <= x1; x++)
        for (uint8_t y = y0; y <= y1; y++) g.A->fb[y >> 3][x] ^= (uint8_t)(1u << (y & 7u));
}
static void draw(void) {
    const app_api_t *A = g.A;
    char s[24], t[TEXT_MAX];
    A->display_clear();
    A->status_clear();
    T(t, T_TITLE);
    A->print_inverse(t, 2, 0, true, true, (uint8_t)(2u + 4u * slen(t)));
    if (g.down) { T(t, T_TON); A->print_inverse(t, 62, 0, true, true, 74); }
    A->draw_battery();
    bool empty = true;
    for (uint8_t r = 0; r < ROWS; r++) {
        if (g.rows[r][0]) empty = false;
        A->print_normal(g.rows[r], 0, 0, r);
    }
    if (empty)
        for (uint8_t i = 0; i < 4u; i++)
            A->print_tiny(T(t, (uint16_t)(T_HELP + i * T_HELP_STRIDE)), 0, (uint8_t)(4u + 9u * i), false, true);
    A->print_normal(g.pat, 0, 0, 5);
    put(putu(s, 1200u / g.dot), T(t, g.cfg.oto ? T_OTO : T_WPM));
    A->print_normal(s, 80, 0, 5);
    /* the level: a bar scaled to the loudest mark, the threshold a tick */
    uint32_t fs = (uint32_t)(g.peak > g.on ? g.peak : g.on) * 5u / 4u;
    if (fs < 16u) fs = 16u;
    uint32_t x = (uint32_t)g.lvl * BAR_W / fs, th = (uint32_t)g.on * BAR_W / fs;
    if (x > BAR_W) x = BAR_W;
    if (th > BAR_W) th = BAR_W;
    fill(0, BAR_W, 49, 49);
    if (x) fill(0, (uint8_t)x, 50, 54);
    fill((uint8_t)th, (uint8_t)th, 47, 55);
    char *o = put(s, "H");
    o = putu(o, g.cfg.sens);
    put(o, g.cfg.mode ? " R" : " D");
    A->print_tiny(s, 106, 50, false, true);
    A->blit_status();
    A->blit_full();
}

__attribute__((section(".text.entry"), used))
void app_main(const app_api_t *api) {
    g.A = api;
    g.raw = g.key = APP_KEY_INVALID;
    api->cfg_load((uint8_t *)&g.cfg, sizeof g.cfg);
    if (g.cfg.magic != CFG_MAGIC || !g.cfg.sens || g.cfg.sens > SENS_MAX || g.cfg.mode > 1u
        || g.cfg.wpm < WPM_MIN || g.cfg.wpm > WPM_MAX || g.cfg.oto > 1u) {
        g.cfg.magic = CFG_MAGIC; g.cfg.sens = 5; g.cfg.mode = 0; g.cfg.wpm = 15; g.cfg.oto = 0;
    }
    setSpeed();
    clearSym();
    g.reg31 = api->bk_read(REG_31);
    mic();
    g.now = g.edge = api->ticks_ms();
    g.floorQ = (uint32_t)(api->bk_read(REG_64) & 0x7FFFu) << 4;
    g.devQ = g.floorQ >> 2;                     /* a cautious start: the spread shrinks to the room's */
    api->backlight_on();
    g.dirty = true;
    while (!g.quit) {
        g.now = api->ticks_ms();
        usb();
        keys();
        sample();
        gaps();
        if (g.now - g.batT >= BAT_MS) { g.batT = g.now; api->battery_sample(); }
        api->backlight_update();
        if ((g.dirty || g.now - g.drawT >= DRAW_MS) && !g.saver) { g.dirty = false; g.drawT = g.now; draw(); }
        api->delay_ms(POLL_MS);
    }
    api->led(false);
    api->bk_write(REG_31, g.reg31);
    api->tones_off_rx();                        /* the receiver back on */
    api->cfg_save((const uint8_t *)&g.cfg, sizeof g.cfg);
}
