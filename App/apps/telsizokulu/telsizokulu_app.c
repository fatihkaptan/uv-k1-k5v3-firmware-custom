/*
 * Telsiz Okulu ("radio school") - learn amateur radio on the radio itself.
 * Turkish texts, ASCII letters. API level 3 (draw_frequency, append_u32), no
 * capability required; nothing is ever transmitted. See README.md.
 *
 *   1 Sinav           10-question rounds: a bank of 30 questions plus
 *                     generated ones (Q codes both ways, which band a
 *                     frequency is in, Ohm's law); the best score is saved
 *   2 Q kodlari       flash cards: the code, MENU shows its meaning
 *   3 Fonetik alfabe  type a callsign (multi-tap), read it out in the ITU
 *                     alphabet; empty: the whole alphabet
 *   4 Bant plani      what the VFO frequency is for (IARU Region 1 summary
 *                     and a few services); UP / DOWN browse the plan
 *   5 Anten hesabi    wavelength, 1/4, 1/2 and 5/8 wave lengths for the VFO
 *                     frequency or one typed in MHz
 *
 * The long texts (questions, band plan, Q code meanings) are compressed with
 * a dictionary built by gen_assets.py: a byte 0x80 + k stands for entry k.
 */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../app_api.h"
#include "telsizokulu_assets.h"     /* generated by gen_assets.py */

#define NQ        10u     /* questions per round                      */
#define NPHON     37u     /* A-Z, 0-9, '/'                            */
#define NMENU     5u
#define ROWS      6u      /* list rows below the speller's input line */
#define IN_MAX    16u
#define TAP_MS    900u
#define LONG_MS   700u
#define REP_MS    150u
#define POLL_MS   10u
#define BAT_MS    5000u
#define CFG_MAGIC 0x4Fu   /* 'O' */
#define NONE      0xFFu
#define UNIT_CM   4u
#define UNIT_M    5u
#define C_LIGHT   2997924580u   /* speed of light, in (10 Hz units) x cm   */

enum { V_MENU, V_QUIZ, V_QCODE, V_PHON, V_BAND, V_ANT };

typedef struct { uint8_t magic, best, sel; } cfg_t;              /* cfg_save */
typedef struct { uint32_t lo, hi; uint16_t txt; } seg_t;         /* 10 B asset record */

static struct {
    uint8_t  view, sel, n, top;        /* screen, menu item, card/segment, list top */
    uint8_t  raw, key, tapKey, tapIdx, inLen;
    uint8_t  qn, score, right, chosen; /* quiz                                 */
    bool     held, tap, dirty, quit, saver, reveal, vfo;
    cfg_t    cfg;
    const app_api_t *A;
    uint32_t now, keyT, repT, tapT, batT, used, khz;
    char     in[IN_MAX + 1];
    struct quiz *Q;                    /* on app_main's stack                  */
} g;

struct quiz {
    char q[64];                        /* the question                         */
    char opt[4][17];                   /* its answers, the right one at right  */
};

/* ---- freestanding helpers (the host test uses the C library's) ---- */
#ifndef HOST_TEST
void *memset(void *d, int c, size_t n) {
    uint8_t *p = d; while (n) p[--n] = (uint8_t)c; return d;
}
void *memcpy(void *d, const void *s, size_t n) {
    uint8_t *p = d; const uint8_t *q = s;
    while (n) { --n; p[n] = q[n]; } return d;
}
/* Divisions through the resident helpers (API level 2). */
uint64_t __aeabi_uidivmod(uint32_t n, uint32_t d) { return g.A->uidivmod(n, d); }
uint64_t __aeabi_uidiv(uint32_t n, uint32_t d) __attribute__((alias("__aeabi_uidivmod")));
#endif

/* ---- text ---- */
static char *T(char *b, uint16_t off) { g.A->asset_read(off, b, TEXT_MAX); return b; }
static char *put(char *o, const char *s) { while (*s) *o++ = *s++; *o = '\0'; return o; }
static char *putT(char *o, uint16_t off) { char t[TEXT_MAX]; return put(o, T(t, off)); }
static char *putu(char *o, uint32_t u) { o = g.A->append_u32(o, u); *o = '\0'; return o; }
static uint8_t slen(const char *s) { uint8_t n = 0; while (s[n]) n++; return n; }
static uint16_t rd16(uint16_t off) { uint16_t v; g.A->asset_read(off, &v, 2); return v; }
/* v / p with the decimals of p (10, 100, 1000): putDec(o, 145500, 1000) "145.500" */
static char *putDec(char *o, uint32_t v, uint32_t p) {
    o = g.A->append_u32(o, v / p);
    *o++ = '.';
    while (p /= 10u) *o++ = (char)('0' + v / p % 10u);
    *o = '\0';
    return o;
}
static char *putKhz(char *o, uint32_t khz) { return putDec(o, khz, 1000u); }
/* v - 1 or v + 1 (DOWN) in 0 .. n-1, wrapping */
static uint8_t step(uint8_t v, uint8_t n, uint8_t k) {
    if (k == APP_KEY_DOWN) return v + 1u < n ? (uint8_t)(v + 1u) : 0;
    return v ? (uint8_t)(v - 1u) : (uint8_t)(n - 1u);
}
/* Compressed text at off, expanded into o up to its nul-th NUL (kept). */
static char *unz(char *o, uint16_t off, uint8_t nul) {
    for (;;) {
        uint8_t c;
        g.A->asset_read(off++, &c, 1);
        if (c & 0x80u) {
            const uint16_t e = (uint16_t)(DICT_OFF + 2u * (c & 0x7Fu));
            const uint16_t a = rd16(e), b = rd16((uint16_t)(e + 2u));
            g.A->asset_read((uint16_t)(DICT + a), o, (uint16_t)(b - a));
            o += b - a;
        } else {
            *o++ = (char)c;
            if (!c && !--nul) return o;
        }
    }
}
static void qcMean(char *o, uint8_t i) { unz(o, (uint16_t)(QC_TXT + rd16((uint16_t)(QC_MEAN + 2u * i))), 1); }
static char *qcCode(char *o, uint8_t i) { return putT(o, (uint16_t)(QC_CODE + i * QC_CODE_STRIDE)); }
static uint32_t rnd(uint32_t n) { return g.A->rand32() % n; }

/* ---- screen helpers: status title, 6x7 lines (18 columns), word wrap ---- */
static void title(const char *t) {
    const app_api_t *A = g.A;
    A->display_clear();
    A->status_clear();
    A->print_inverse(t, 2, 0, true, true, (uint8_t)(2u + 4u * slen(t)));
    A->draw_battery();
}
static void line(const char *s, uint8_t l) { g.A->print_normal(s, 0, 0, l); }
static void center(const char *s, uint8_t l) { g.A->print_normal(s, 0, 127, l); }
static void invert(uint8_t l) { for (uint8_t x = 0; x < 128u; x++) g.A->fb[l][x] ^= 0xFFu; }
static void hint(const char *s) { g.A->print_tiny(s, 0, 50, false, true); }
static void hintT(uint16_t off) { char t[TEXT_MAX]; hint(T(t, off)); }
static void menuText(char *o, uint8_t i) { putT(o, (uint16_t)(T_MENU + i * T_MENU_STRIDE)); }
/* s on lines l .. end-1, broken at spaces */
static void wrap(const char *s, uint8_t l, uint8_t end) {
    char b[19];
    while (*s && l < end) {
        uint8_t n = 0;
        while (s[n] && n < 18u) n++;
        if (s[n] && s[n] != ' ') {                 /* mid-word: back to a space */
            uint8_t k = n;
            while (k && s[k - 1] != ' ') k--;
            if (k) n = k;
        }
        for (uint8_t i = 0; i < n; i++) b[i] = s[i];
        b[n] = '\0';
        line(b, l++);
        s += n;
        while (*s == ' ') s++;
    }
}
static void tone(bool good) { g.A->play_tone(good ? 1500u : 300u, good ? 80u : 250u); }

/* ---- quiz ---- */
static void pick(uint8_t n, uint8_t *idx) {        /* four different indexes < n */
    for (uint8_t k = 0; k < 4u; k++) {
        uint8_t v, j;
        do {
            v = (uint8_t)rnd(n);
            for (j = 0; j < k && idx[j] != v; j++) {}
        } while (j < k);
        idx[k] = v;
    }
}
static void newQ(void) {
    char *q = g.Q->q;
    uint8_t idx[4];
    const uint8_t type = (uint8_t)rnd(20);
    g.chosen = NONE;
    if (type < 10u) {                              /* the bank, no repeat in a round */
        uint8_t i = (uint8_t)rnd(NFIX);
        while (g.used & (1u << i)) if (++i >= NFIX) i = 0;
        g.used |= 1u << i;
        char b[FIX_MAX + 1], *p = b;
        unz(b, (uint16_t)(FIX + rd16((uint16_t)(FIX_OFF + 2u * i))), 5);
        put(g.Q->q, p);                            /* question NUL answer NUL x4 */
        for (uint8_t k = 0; k < 4u; k++) { p += slen(p) + 1; put(g.Q->opt[k], p); }
    } else if (type < 15u) {                       /* Q codes, both ways */
        const bool rev = type >= 13u;
        pick(NQC, idx);
        for (uint8_t k = 0; k < 4u; k++) {
            if (rev) qcCode(g.Q->opt[k], idx[k]); else qcMean(g.Q->opt[k], idx[k]);
        }
        *q++ = '\'';
        if (rev) qcMean(q, idx[0]); else qcCode(q, idx[0]);
        putT(q + slen(q), rev ? T_QR : T_QF);
    } else if (type < 17u) {                       /* the band of a frequency */
        uint32_t r[2];
        pick(NBAND, idx);
        for (uint8_t k = 0; k < 4u; k++) putT(g.Q->opt[k], (uint16_t)(BAND_NAME + idx[k] * BAND_NAME_STRIDE));
        g.A->asset_read((uint16_t)(BAND_KHZ + 8u * idx[0]), r, 8);
        putT(putKhz(q, r[0] + 5u * rnd((r[1] - r[0]) / 5u)), T_BQ);
    } else {                                       /* Ohm's law */
        uint32_t v[4];
        const uint32_t a = 1u + rnd(6), r = 2u + rnd(11);   /* "...U=12 V, R=4 ohm ise akim I=?" */
        putT(putu(putT(putu(putT(q, T_OHM), a * r), T_OHM2), r), T_OHM3);
        v[0] = a;
        if (a < 4u) { v[1] = a + 1u; v[2] = a + 2u; v[3] = a + 3u; }
        else        { v[1] = 2u * a; v[2] = a + a / 2u; v[3] = a / 2u; }
        for (uint8_t k = 0; k < 4u; k++)
            putT(putu(g.Q->opt[k], v[k]), (uint16_t)(T_UNIT + 1u * T_UNIT_STRIDE));   /* " A" */
    }
    /* the right answer (opt[0]) to a random place */
    g.right = (uint8_t)rnd(4);
    for (uint8_t i = 0; i < sizeof g.Q->opt[0]; i++) {
        const char c = g.Q->opt[0][i];
        g.Q->opt[0][i] = g.Q->opt[g.right][i]; g.Q->opt[g.right][i] = c;
    }
}
static void startQuiz(void) { g.qn = 0; g.score = 0; g.used = 0; newQ(); }
static void quizKey(uint8_t k) {
    if (g.qn >= NQ) {                              /* results */
        if (k == APP_KEY_MENU) startQuiz();
        return;
    }
    if (g.chosen == NONE) {
        if (k < APP_KEY_1 || k > APP_KEY_4) return;
        g.chosen = (uint8_t)(k - APP_KEY_1);
        const bool ok = g.chosen == g.right;
        g.score = (uint8_t)(g.score + ok);
        tone(ok);
        return;
    }
    if (++g.qn < NQ) newQ();                       /* any key: the next one */
    else if (g.score > g.cfg.best) g.cfg.best = g.score;
}
static char *putScore(char *o, uint8_t s) { return put(putu(o, s), "/10"); }
static void drawQuiz(void) {
    char s[24], t[TEXT_MAX];
    if (g.qn >= NQ) {
        menuText(s, 0);
        title(s);
        putScore(s, g.score);
        g.A->print_string(s, 0, 127, 1, 10);
        center(T(t, (uint16_t)(T_VERDICT + (g.score >= 8u ? 0u : g.score >= 5u ? 1u : 2u) * T_VERDICT_STRIDE)), 4);
        putScore(putT(s, T_BEST), g.cfg.best);
        center(s, 5);
        hintT(T_AGAIN);
        return;
    }
    putScore(putT(s, T_SORU), (uint8_t)(g.qn + 1u));              /* "SORU 3/10" */
    title(s);
    if (g.chosen != NONE) {
        T(t, g.chosen == g.right ? T_OK : T_BAD);
        g.A->print_inverse(t, 50, 0, true, true, (uint8_t)(50u + 4u * slen(t)));
    }
    wrap(g.Q->q, 0, 3);
    for (uint8_t k = 0; k < 4u; k++) {
        s[0] = (char)('1' + k); s[1] = ' ';
        put(s + 2, g.Q->opt[k]);
        line(s, (uint8_t)(3u + k));
        if (g.chosen != NONE && k == g.right) invert((uint8_t)(3u + k));
    }
}

/* ---- Q code cards ---- */
static void drawQcode(void) {
    char s[32];
    menuText(s, 1);
    title(s);
    qcCode(s, g.n);
    g.A->print_string(s, 0, 127, 1, 10);
    if (g.reveal) qcMean(s, g.n); else put(s, "?");
    center(s, 4);
    putT(putu(put(putu(s, g.n + 1u), "/"), NQC), T_QHINT);       /* "3/22  MENU ..." */
    hint(s);
}

/* ---- phonetic speller ---- */
static void typeKey(uint8_t k) {
    char m[KEYMAP_STRIDE];
    g.A->asset_read((uint16_t)(KEYMAP + k * KEYMAP_STRIDE), m, KEYMAP_STRIDE);
    if (g.tap && g.tapKey == k) {
        if (!m[++g.tapIdx]) g.tapIdx = 0;
        g.in[g.inLen - 1] = m[g.tapIdx];
    } else {
        if (g.inLen >= IN_MAX) { tone(false); return; }
        g.in[g.inLen++] = m[0];
        g.tap = true; g.tapKey = k; g.tapIdx = 0;
    }
    g.in[g.inLen] = '\0';
    g.tapT = g.now;
    g.top = g.inLen > ROWS ? (uint8_t)(g.inLen - ROWS) : 0;
}
static void drawPhon(void) {
    char s[32], b[PHON_LEN];
    menuText(s, 2);
    title(s);
    if (g.inLen) {
        line(g.in, 0);
        uint8_t *p = g.A->fb[0] + (g.inLen - (g.tap ? 1u : 0u)) * 7u;
        for (uint8_t i = 0; i < 7u; i++) p[i] ^= 0x7Fu;        /* block cursor */
    } else g.A->print_tiny(T((char *)b, T_CALL), 1, 1, false, true);
    for (uint8_t x = 0; x < 128u; x++) g.A->fb[0][x] |= 0x80u;  /* rule, y 7 */
    g.A->asset_read(PHON, b, PHON_LEN);
    const uint8_t count = g.inLen ? g.inLen : NPHON;
    for (uint8_t r = 0; r < ROWS && g.top + r < count; r++) {
        const uint8_t i = (uint8_t)(g.top + r);
        char c = (char)(i < 26u ? 'A' + i : i < 36u ? '0' + i - 26 : '/');
        uint8_t w = i < 36u ? i : NONE;
        if (g.inLen) {
            c = g.in[i];
            w = c >= 'A' && c <= 'Z' ? (uint8_t)(c - 'A') : c >= '0' && c <= '9' ? (uint8_t)(26 + c - '0') : NONE;
        }
        s[0] = c; s[1] = ' '; s[2] = '='; s[3] = ' '; s[4] = '\0';
        if (w != NONE) {
            const char *p = b;
            while (w--) while (*p++) {}
            put(s + 4, p);
        } else if (c == '/') putT(s + 4, T_STROKE);
        line(s, (uint8_t)(1u + r));
    }
}

/* ---- band plan ---- */
static void seg(uint8_t i, seg_t *s) { g.A->asset_read((uint16_t)(SEG + i * SEG_REC), s, SEG_REC); }
static uint8_t findSeg(uint32_t khz) {
    seg_t s;
    for (uint8_t i = 0; i < NSEG; i++) {
        seg(i, &s);
        if (khz >= s.lo && khz < s.hi) return i;
    }
    return NONE;
}
static void drawBand(void) {
    char s[64];
    seg_t sg = { 0, 0, 0 };
    menuText(s, 3);
    title(s);
    if (g.n != NONE) seg(g.n, &sg);
    g.A->draw_frequency(g.vfo ? g.khz * 100u : sg.lo * 100u, 8, 0);
    if (g.n == NONE) wrap(T(s, T_NOTLIST), 3, 6);
    else {
        putKhz(put(putKhz(s, sg.lo), "-"), sg.hi);
        center(s, 2);
        unz(s, (uint16_t)(SEG_TXT + sg.txt), 1);
        wrap(s, 3, 6);
    }
    hintT(T_BANDHINT);
}

/* ---- antenna lengths ---- */
static uint32_t antKhz(void) {
    if (!g.inLen) return g.khz;
    uint32_t mhz = 0, frac = 0;
    uint8_t fd = 0;
    bool dot = false;
    for (uint8_t i = 0; i < g.inLen; i++) {
        const uint8_t d = (uint8_t)(g.in[i] - '0');
        if (g.in[i] == '.') dot = true;
        else if (!dot) mhz = mhz * 10u + d;
        else if (fd < 3u) { frac = frac * 10u + d; fd++; }
    }
    while (fd < 3u) { frac *= 10u; fd++; }
    return mhz * 1000u + frac;
}
static void drawAnt(void) {
    char s[24];
    menuText(s, 4);
    title(s);
    const uint32_t khz = antKhz();
    if (g.inLen) put(putT(s, T_F), g.in); else putKhz(putT(s, T_VFO), khz);
    putT(s + slen(s), T_MHZ);
    line(s, 0);
    if (khz >= 1000u && khz <= 2000000u) {
        const uint32_t f10 = khz * 100u;          /* 10 Hz units */
        const uint32_t lam = C_LIGHT / f10 * 10u + C_LIGHT % f10 * 10u / f10;   /* mm */
        /* x 4096, rounded: the wavelength, then 0.95 x 1/4, 1/2 and 5/8 */
        static const uint16_t k[4] = { 4096u, 973u, 1946u, 2432u };
        for (uint8_t r = 0; r < 4u; r++) {
            const uint32_t mm = (lam * k[r] + 2048u) >> 12;
            const bool m = mm >= 10000u;           /* "10.71 m", else "48.9 cm" */
            putT(putDec(s, m ? mm / 10u : mm, m ? 100u : 10u),
                 (uint16_t)(T_UNIT + (m ? UNIT_M : UNIT_CM) * T_UNIT_STRIDE));
            const uint8_t l = (uint8_t)(2u + r);
            g.A->print_normal(s, (uint8_t)(127u - 7u * slen(s)), 0, l);
            char t[TEXT_MAX];
            line(T(t, (uint16_t)(T_ANT + r * T_ANT_STRIDE)), l);
        }
    } else center("?", 3);
    hintT(T_ANTHINT);
}

/* ---- menu ---- */
static void enter(uint8_t v) {
    g.view = v;
    g.n = 0; g.top = 0; g.inLen = 0; g.in[0] = '\0'; g.tap = false; g.reveal = false;
    g.khz = g.A->rx_freq() / 100u;
    if (v == V_QUIZ) startQuiz();
    if (v == V_BAND) { g.vfo = true; g.n = findSeg(g.khz); }
}
static void drawMenu(void) {
    char s[24], t[TEXT_MAX];
    title(T(t, T_TITLE));
    for (uint8_t i = 0; i < NMENU; i++) {
        s[0] = (char)('1' + i); s[1] = ' ';
        menuText(s + 2, i);
        line(s, i);
        if (i == g.sel) invert(i);
    }
    hintT(T_HINT);
}

/* ---- keys ---- */
static void onPress(uint8_t k) {
    g.dirty = true;
    const bool digit = k <= APP_KEY_9;
    if (!digit || k != g.tapKey) g.tap = false;
    switch (g.view) {
    case V_MENU:
        if (k >= APP_KEY_1 && k <= APP_KEY_5) { g.sel = (uint8_t)(k - APP_KEY_1); enter((uint8_t)(V_QUIZ + g.sel)); }
        else if (k == APP_KEY_MENU) enter((uint8_t)(V_QUIZ + g.sel));
        else if (k == APP_KEY_UP || k == APP_KEY_DOWN) g.sel = step(g.sel, NMENU, k);
        else if (k == APP_KEY_EXIT) g.quit = true;
        return;
    case V_QUIZ:
        if (k == APP_KEY_EXIT) break;
        quizKey(k);
        return;
    case V_QCODE:
        if (k == APP_KEY_MENU) g.reveal = !g.reveal;
        else if (k == APP_KEY_UP || k == APP_KEY_DOWN) { g.n = step(g.n, NQC, k); g.reveal = false; }
        else if (k == APP_KEY_EXIT) break;
        return;
    case V_BAND:
        if (k == APP_KEY_MENU) { g.vfo = true; g.n = findSeg(g.khz); }
        else if (k == APP_KEY_UP || k == APP_KEY_DOWN) {
            g.n = g.n == NONE ? 0 : step(g.n, NSEG, k);
            g.vfo = false;
        } else if (k == APP_KEY_EXIT) break;
        return;
    default:                                       /* V_PHON, V_ANT: a typed line */
        if (k == APP_KEY_EXIT) {
            if (!g.inLen) break;
            g.in[--g.inLen] = '\0';
            g.top = g.inLen > ROWS ? (uint8_t)(g.inLen - ROWS) : 0;
        } else if (k == APP_KEY_MENU) { g.inLen = 0; g.in[0] = '\0'; g.top = 0; }
        else if (g.view == V_PHON) {
            if (digit) typeKey(k);
            else if (k == APP_KEY_UP && g.top) g.top--;
            else if (k == APP_KEY_DOWN && g.top + ROWS < (g.inLen ? g.inLen : NPHON)) g.top++;
        } else if ((digit || (k == APP_KEY_STAR && g.inLen)) && g.inLen < 8u) {
            g.in[g.inLen++] = digit ? (char)('0' + k) : '.';   /* a 2nd '.' reads as none */
            g.in[g.inLen] = '\0';
        }
        return;
    }
    enter(V_MENU);                                  /* EXIT: back to the menu */
}
static void onLong(uint8_t k) {
    if (g.view == V_PHON && k <= APP_KEY_9 && g.tap && g.tapKey == k) {
        g.in[g.inLen - 1] = (char)('0' + k);       /* the letter this press typed -> digit */
        g.tap = false; g.dirty = true;
    }
}
static void keys(void) {
    const uint8_t k = g.A->get_key();
    if (k == APP_KEY_SAVER) { g.saver = true; return; }
    g.saver = false;
    if (k == APP_KEY_WAKE) { g.dirty = true; g.raw = g.key = APP_KEY_INVALID; return; }
    if (k != g.raw) { g.raw = k; return; }          /* debounce: two equal readings */
    if (k == g.key) {                               /* still held */
        if (k == APP_KEY_INVALID) return;
        if (!g.held) {
            if (g.now - g.keyT >= LONG_MS) { g.held = true; g.repT = g.now; onLong(k); }
        } else if ((k == APP_KEY_UP || k == APP_KEY_DOWN) && g.now - g.repT >= REP_MS) {
            g.repT = g.now; onPress(k);
        }
        return;
    }
    g.key = k; g.held = false; g.keyT = g.now;
    if (k != APP_KEY_INVALID) onPress(k);
}

__attribute__((noinline))
static void draw(void) {
    switch (g.view) {
    case V_MENU:  drawMenu(); break;
    case V_QUIZ:  drawQuiz(); break;
    case V_QCODE: drawQcode(); break;
    case V_PHON:  drawPhon(); break;
    case V_BAND:  drawBand(); break;
    default:      drawAnt(); break;
    }
    g.A->blit_status();
    g.A->blit_full();
}

__attribute__((section(".text.entry"), used))
void app_main(const app_api_t *api) {
    struct quiz quiz;                   /* on the stack: the overlay holds the code */
    g.A = api; g.Q = &quiz;
    g.raw = g.key = g.tapKey = APP_KEY_INVALID;
    api->cfg_load((uint8_t *)&g.cfg, sizeof g.cfg);
    if (g.cfg.magic != CFG_MAGIC || g.cfg.best > NQ || g.cfg.sel >= NMENU) {
        g.cfg.magic = CFG_MAGIC; g.cfg.best = 0; g.cfg.sel = 0;
    }
    g.sel = g.cfg.sel;
    api->backlight_on();
    g.dirty = true;
    while (!g.quit) {
        g.now = api->ticks_ms();
        keys();
        if (g.tap && g.now - g.tapT >= TAP_MS) { g.tap = false; g.dirty = true; }
        if (g.now - g.batT >= BAT_MS) { g.batT = g.now; api->battery_sample(); g.dirty = true; }
        api->backlight_update();
        if (g.dirty && !g.saver) { g.dirty = false; draw(); }
        api->delay_ms(POLL_MS);
    }
    g.cfg.sel = g.sel;
    api->cfg_save((const uint8_t *)&g.cfg, sizeof g.cfg);
}
