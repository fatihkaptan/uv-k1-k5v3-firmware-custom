/*
 * Anten Lab - the radiation pattern of a directional antenna, measured with
 * the radio's RSSI while the antenna turns toward a steady signal (a beacon,
 * a repeater, a friend's carrier). API level 3, receive only. See README.md.
 *
 * ADIM: point, MENU, the radio averages 16 readings for that bearing and
 * steps 10 degrees. TUR: MENU, 3 s countdown, then turn the antenna once,
 * evenly, clockwise, in the chosen time (beeps every 90 degrees); the
 * readings are binned by time. 36 bins of 10 degrees, quarter-dB values.
 *
 * On screen: the polar pattern (0 dB at the circle, rings at -10 and -20,
 * 30 dB shown), the peak's bearing and level, front-to-back ratio, the -3 dB
 * beamwidth (interpolated) and the live level. A reference (key 4) is drawn
 * dotted over the next measurement, on the same dB scale: two antennas, or
 * before / after an adjustment. AGC off, fixed gain, an attenuator (Fox
 * Hunt's REG_13 steps) for strong signals, compensated in the readings.
 * Both patterns are kept across restarts (APP_FLAG_SAVE_SCREEN). F sends
 * the pattern to the computer as CSV (tools/antenlab/antenlab.py).
 */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../app_api.h"
#include "antenlab_assets.h"     /* generated by gen_assets.py */

#define NB        36u      /* bins of 10 degrees                        */
#define NOVAL     (-32768)
#define DYN       120      /* 30 dB in quarter dB: the plot's range     */
#define CX        28       /* plot centre and radius                    */
#define CY        28
#define R         26
#define PX        58u      /* the text panel's first column             */
#define POLL_MS   10u
#define LIVE_MS   150u
#define BAT_MS    5000u
#define MSG_MS    2000u
#define ATT_SETTLE 40u
#define SAVE_MAGIC 0x414Cu /* "LA"                                      */
#define CFG_MAGIC 0x41u
#define BK_REG_13 0x13
#define BK_REG_67 0x67     /* RSSI, half dB: dBm = value / 2 - 160 + the band's correction */

enum { M_STEP, M_TURN };
enum { P_IDLE, P_COUNT, P_RUN };

typedef struct { uint8_t magic, mode, att, dur, ref, pad[3]; } cfg_t;
typedef struct { uint16_t magic, pad; int16_t cur[NB], ref[NB]; } save_t;   /* the kept block */
typedef struct { int32_t sum[NB]; uint16_t cnt[NB]; } acc_t;

static struct {
    uint8_t  dir, phase, beeps, raw, key, last;
    bool     dirty, quit, saver, host, msg;
    cfg_t    cfg;
    const app_api_t *A;
    save_t  *S;
    acc_t   *C;                        /* both on app_main's stack             */
    int16_t  live;                     /* quarter dBm                          */
    int8_t   corr;                     /* rssi_dbm() - the register's dBm      */
    uint32_t now, t0, tBeep, liveT, batT, msgT;
} g;

#ifndef HOST_TEST
void *memset(void *d, int c, size_t n) { uint8_t *p = d; while (n) p[--n] = (uint8_t)c; return d; }
void *memcpy(void *d, const void *s, size_t n) {
    uint8_t *p = d; const uint8_t *q = s; while (n) { --n; p[n] = q[n]; } return d;
}
uint64_t __aeabi_uidivmod(uint32_t n, uint32_t d) { return g.A->uidivmod(n, d); }
uint64_t __aeabi_uidiv(uint32_t n, uint32_t d) __attribute__((alias("__aeabi_uidivmod")));
uint64_t __aeabi_idivmod(int32_t n, int32_t d) { return g.A->idivmod(n, d); }
uint64_t __aeabi_idiv(int32_t n, int32_t d) __attribute__((alias("__aeabi_idivmod")));
#endif

static char *T(char *b, uint16_t off) { g.A->asset_read(off, b, TEXT_MAX); return b; }
static char *put(char *o, const char *s) { while (*s) *o++ = *s++; *o = '\0'; return o; }
static char *putT(char *o, uint16_t off) { char t[TEXT_MAX]; return put(o, T(t, off)); }
static char *putu(char *o, uint32_t u) { o = g.A->append_u32(o, u); *o = '\0'; return o; }
static uint8_t slen(const char *s) { uint8_t n = 0; while (s[n]) n++; return n; }
static bool due(uint32_t t) { return (int32_t)(g.now - t) >= 0; }
/* quarter dB as "-71.2" (decimals 1) or "-71.25" (decimals 2) */
static char *putQ(char *o, int32_t q, uint8_t decimals) {
    if (q < 0) { *o++ = '-'; q = -q; }
    o = putu(o, (uint32_t)q >> 2);
    *o++ = '.';
    const uint8_t f = (uint8_t)((q & 3) * 25);
    *o++ = (char)('0' + f / 10u);
    if (decimals > 1u) *o++ = (char)('0' + f % 10u);
    *o = '\0';
    return o;
}
static int8_t sinT(uint8_t k) { int8_t v; g.A->asset_read((uint16_t)(SIN + k % NB), &v, 1); return v; }

/* ---- radio: AGC off, fixed gain, the attenuator ---- */
static uint8_t attDb(void) { uint8_t d; g.A->asset_read((uint16_t)(ATT_DB + g.cfg.att), &d, 1); return d; }
static void applyAtt(void) {
    uint16_t gain, reg = g.A->bk_read(BK_REG_13);
    g.A->asset_read((uint16_t)(ATT_REG13 + 2u * g.cfg.att), &gain, 2);
    g.A->bk_write(BK_REG_13, (uint16_t)((reg & ~0x03FFu) | gain));
    g.A->delay_ms(ATT_SETTLE);
}
/* RSSI straight from REG_67 (half-dB steps; rssi_dbm() rounds to 1 dB),
 * with the band correction rssi_dbm() applies, measured once. */
static uint16_t reg67(void) { return g.A->bk_read(BK_REG_67) & 0x01FFu; }
static void calib(void) {
    for (uint8_t i = 0; i < 8u; i++) {
        const uint16_t a = reg67();
        const int16_t d = g.A->rssi_dbm();
        if (a == reg67()) { g.corr = (int8_t)(d - ((int16_t)(a >> 1) - 160)); return; }
    }
}
static int16_t offset(void) { return (int16_t)(4 * (g.corr + attDb()) - 640); }
static int16_t sample(void) { return (int16_t)(2 * reg67() + offset()); }      /* quarter dB */
static int16_t measure(void) {                  /* 16 readings, 8 ms apart */
    int32_t s = 0;
    for (uint8_t i = 0; i < 16u; i++) { s += reg67(); g.A->delay_ms(8); }
    return (int16_t)(s / 8 + offset());
}
static void beep(uint16_t hz, uint16_t ms) { g.A->play_tone(hz, ms); g.A->set_agc(false); applyAtt(); }
static uint16_t pitch(int16_t q) {              /* -130 .. -40 dBm -> 400 .. 2200 Hz */
    int32_t v = 400 + (q / 4 + 130) * 20;
    return (uint16_t)(v < 400 ? 400 : v > 2200 ? 2200 : v);
}

/* ---- the pattern's numbers ---- */
static uint8_t peak(const int16_t *p) {
    uint8_t k = 0;
    for (uint8_t i = 1; i < NB; i++) if (p[i] > p[k]) k = i;
    return k;
}
/* 0.1 degrees from the peak to the -3 dB point, one way (+1 / -1 bin) */
static int32_t half(const int16_t *p, uint8_t k, int8_t way) {
    const int32_t thr = p[k] - 12;
    for (uint8_t n = 1; n <= NB / 2u; n++) {
        const int16_t a = p[(k + NB + way * (n - 1)) % NB], b = p[(k + NB + way * n) % NB];
        if (a == NOVAL || b == NOVAL) return -1;
        if (b < thr) return 100 * (n - 1) + 100 * (a - thr) / (a - b);
    }
    return -1;
}

/* The main beam: between the -3 dB points when both are found (the level
 * quantisation flattens a peak), else the strongest bin. 0.1 degrees. */
typedef struct { int16_t beam, level, fb, bw; } stat_t;
static void stats(const int16_t *p, stat_t *st) {
    const uint8_t k = peak(p);
    st->level = p[k]; st->beam = st->fb = st->bw = NOVAL;
    if (p[k] == NOVAL) return;
    const int32_t a = half(p, k, -1), z = half(p, k, 1);
    int32_t b = 100 * k;
    if (a >= 0 && z >= 0) { st->bw = (int16_t)(a + z); b += (z - a) / 2; }
    st->beam = (int16_t)((b + 3600) % 3600);
    const int16_t back = p[((st->beam + 50) / 100 + NB / 2u) % NB];
    if (back != NOVAL) st->fb = (int16_t)(p[k] - back);
}

/* ---- sweep (TUR) ---- */
static const uint8_t DUR[4] = { 10, 20, 30, 60 };
static void turnStart(void) {
    memset(g.C, 0, sizeof *g.C);
    g.phase = P_COUNT; g.beeps = 0; g.tBeep = g.now; g.dirty = true;
}
static void turnEnd(bool keep) {
    if (keep)
        for (uint8_t i = 0; i < NB; i++)
            if (g.C->cnt[i]) g.S->cur[i] = (int16_t)(g.C->sum[i] / g.C->cnt[i]);
    g.phase = P_IDLE; g.dirty = true;
    beep(keep ? 1500u : 300u, keep ? 300u : 150u);
}
static void turnStep(void) {
    if (g.phase == P_COUNT) {                    /* 3 2 1, then go */
        if (!due(g.tBeep)) return;
        if (g.beeps < 3u) { beep(800, 60); g.beeps++; g.tBeep += 1000u; g.dirty = true; return; }
        beep(1600, 120);
        g.phase = P_RUN; g.t0 = g.now; g.beeps = 1; g.dirty = true;
        return;
    }
    if (g.phase != P_RUN) return;
    const uint32_t span = 1000u * DUR[g.cfg.dur], t = g.now - g.t0;
    if (t >= span) { turnEnd(true); return; }
    const uint8_t b = (uint8_t)((t * NB * 2u / span + 1u) / 2u % NB);   /* bin b: 10b +- 5 degrees */
    g.C->sum[b] += sample(); g.C->cnt[b]++;
    g.dir = b;
    if (t >= span * g.beeps / 4u) { g.beeps++; beep(1200, 40); }   /* every 90 degrees */
    if (b != g.last) { g.last = b; g.dirty = true; }
}

/* ---- USB: the pattern as CSV ---- */
static void out(const char *s) { if (g.host) { g.A->serial_write(APP_SERIAL_USB, s, slen(s)); g.A->serial_write(APP_SERIAL_USB, "\r\n", 2); } }
static void export(void) {
    char s[48], *o;
    out(T(s, T_BANNER));
    out(T(s, T_CSV));
    for (uint8_t i = 0; i < NB; i++) {
        o = putu(s, 10u * i);
        *o++ = ',';
        if (g.S->cur[i] != NOVAL) o = putQ(o, g.S->cur[i], 2);
        *o++ = ',';
        *o = '\0';
        if (g.S->ref[i] != NOVAL) putQ(o, g.S->ref[i], 2);
        out(s);
    }
}

/* ---- keys ---- */
static void onPress(uint8_t k) {
    g.dirty = true;
    if (g.phase) { if (k == APP_KEY_MENU || k == APP_KEY_EXIT) turnEnd(false); return; }
    switch (k) {
    case APP_KEY_MENU:
        if (g.cfg.mode == M_TURN) { turnStart(); break; }
        g.S->cur[g.dir] = measure();
        g.A->play_tone(pitch(g.S->cur[g.dir]), 60);
        g.A->set_agc(false); applyAtt();
        g.dir = (uint8_t)((g.dir + 1u) % NB);
        break;
    case APP_KEY_UP:   g.dir = (uint8_t)((g.dir + 1u) % NB); break;
    case APP_KEY_DOWN: g.dir = (uint8_t)((g.dir + NB - 1u) % NB); break;
    case APP_KEY_1: g.cfg.mode ^= 1u; break;
    case APP_KEY_2: g.cfg.dur = (uint8_t)((g.cfg.dur + 1u) & 3u); break;
    case APP_KEY_3: g.cfg.att = (uint8_t)((g.cfg.att + 1u) & 3u); applyAtt(); break;
    case APP_KEY_4:
        for (uint8_t i = 0; i < NB; i++) g.S->ref[i] = g.S->cur[i];
        g.cfg.ref = 1; g.msg = true; g.msgT = g.now;
        break;
    case APP_KEY_5: g.cfg.ref ^= 1u; break;
    case APP_KEY_0: for (uint8_t i = 0; i < NB; i++) g.S->cur[i] = NOVAL; g.dir = 0; break;
    case APP_KEY_F: export(); break;
    case APP_KEY_EXIT: g.quit = true; break;
    default: break;
    }
}
static void keys(void) {
    const uint8_t k = g.A->get_key();
    if (k == APP_KEY_SAVER) { g.saver = true; return; }
    g.saver = false;
    if (k == APP_KEY_WAKE) { g.dirty = true; g.raw = g.key = APP_KEY_INVALID; return; }
    if (k != g.raw) { g.raw = k; return; }
    if (k == g.key) return;
    g.key = k;
    if (k != APP_KEY_INVALID) onPress(k);
}

/* ---- screen ---- */
static void pt(int16_t x, int16_t y) {
    if (x >= 0 && x < 128 && y >= 0 && y < 56) g.A->fb[y >> 3][x] |= (uint8_t)(1u << (y & 7));
}
static int16_t rad(int16_t q, int16_t top) {    /* level -> radius */
    const int32_t v = q - (top - DYN);
    return (int16_t)(v <= 0 ? 0 : R * v / DYN);
}
static int16_t px(int16_t r, uint8_t k) { return (int16_t)(CX + r * sinT(k) / 127); }
static int16_t py(int16_t r, uint8_t k) { return (int16_t)(CY - r * sinT((uint8_t)(k + 9u)) / 127); }
static void pattern(const int16_t *p, int16_t top, bool dotted) {
    for (uint8_t k = 0; k < NB; k++) {
        const uint8_t j = (uint8_t)((k + 1u) % NB);
        if (p[k] == NOVAL) continue;
        const int16_t r0 = rad(p[k], top), x0 = px(r0, k), y0 = py(r0, k);
        if (dotted) { pt(x0, y0); pt((int16_t)(x0 + 1), y0); pt(x0, (int16_t)(y0 + 1)); }
        if (p[j] == NOVAL) { if (!dotted) pt(x0, y0); continue; }
        const int16_t r1 = rad(p[j], top), x1 = px(r1, j), y1 = py(r1, j);
        if (dotted) pt((int16_t)((x0 + x1) / 2), (int16_t)((y0 + y1) / 2));
        else g.A->draw_line(g.A->fb, x0, y0, x1, y1, true);
    }
}
static void text(char *s, uint8_t line) { g.A->print_normal(s, PX, 0, line); }
static void capsule(uint16_t off, uint8_t x) {
    char t[TEXT_MAX];
    T(t, off);
    g.A->print_inverse(t, x, 0, true, true, (uint8_t)(x + 4u * slen(t)));
}
static void draw(void) {
    const app_api_t *A = g.A;
    const int16_t *c = g.S->cur, *r = g.S->ref;
    char s[24], *o;
    A->display_clear();
    A->status_clear();
    capsule(T_TITLE, 2);
    capsule((uint16_t)(T_MODE + g.cfg.mode * T_MODE_STRIDE), 44);
    if (g.cfg.ref) capsule(T_REF, 66);
    A->draw_battery();

    /* the plot: the outer circle, dots at -10 and -20 dB, north, the bearing */
    for (uint8_t k = 0; k < NB; k++) {
        const uint8_t j = (uint8_t)((k + 1u) % NB);
        A->draw_line(A->fb, px(R, k), py(R, k), px(R, j), py(R, j), true);
        if (!(k & 1u)) { pt(px(R * 2 / 3, k), py(R * 2 / 3, k)); pt(px(R / 3, k), py(R / 3, k)); }
    }
    pt(CX, CY);
    A->draw_line(A->fb, CX, CY, px(R, g.dir), py(R, g.dir), true);
    int16_t top = NOVAL;
    for (uint8_t k = 0; k < NB; k++) {
        if (c[k] > top) top = c[k];
        if (g.cfg.ref && r[k] > top) top = r[k];
    }
    if (top != NOVAL) {
        pattern(c, top, false);
        if (g.cfg.ref) pattern(r, top, true);
    }

    /* the panel */
    if (g.phase == P_COUNT) { s[0] = (char)('4' - g.beeps); put(s + 1, "..."); }   /* 3... 2... 1... */
    else if (g.phase == P_RUN) putT(putu(s, (g.now - g.t0) / 1000u), T_S);
    else if (g.cfg.mode == M_TURN) putT(putu(putT(s, T_SURE), DUR[g.cfg.dur]), T_S);
    else putu(putT(s, T_YON), 10u * g.dir);
    text(s, 0);
    putT(putQ(s, g.live, 1), T_DB);
    text(s, 1);
    stat_t st;
    stats(c, &st);
    if (st.beam != NOVAL) {
        putu(putT(s, T_TEPE), (uint32_t)(st.beam + 5) / 10u % 360u);
        text(s, 2);
        putT(putQ(s, st.level, 1), T_DB);
        text(s, 3);
        if (st.fb != NOVAL) { putT(putQ(putT(s, T_FB), st.fb, 1), T_DB); text(s, 4); }
        if (st.bw != NOVAL) { o = putT(s, T_BW); putu(o, (uint32_t)(st.bw + 5) / 10u); text(s, 5); }
    }
    if (g.msg) A->print_tiny(T(s, T_REFOK), PX, 50, false, true);
    else if (g.cfg.att) { putT(putu(putT(s, T_ATT), attDb()), T_DB); text(s, 6); }
    A->blit_status();
    A->blit_full();
}

__attribute__((section(".text.entry"), used))
void app_main(const app_api_t *api) {
    save_t sv;                          /* on the stack: the overlay holds the code */
    acc_t acc;
    g.A = api; g.S = &sv; g.C = &acc;
    g.raw = g.key = APP_KEY_INVALID;
    api->cfg_load((uint8_t *)&g.cfg, sizeof g.cfg);
    if (g.cfg.magic != CFG_MAGIC || g.cfg.mode > 1u || g.cfg.att > 3u || g.cfg.dur > 3u) {
        memset(&g.cfg, 0, sizeof g.cfg);
        g.cfg.magic = CFG_MAGIC; g.cfg.dur = 1;
    }
    api->asset_read(SAVE, &sv, sizeof sv);
    if (sv.magic != SAVE_MAGIC) {
        sv.magic = SAVE_MAGIC;
        for (uint8_t i = 0; i < NB; i++) sv.cur[i] = sv.ref[i] = NOVAL;
    }
    api->set_af(APP_AF_MUTE);
    api->set_agc(false);
    applyAtt();
    calib();
    g.live = sample();
    api->backlight_on();
    g.dirty = true;
    while (!g.quit) {
        g.now = api->ticks_ms();
        const bool h = (api->serial_ctl(APP_SERIAL_USB, 0) & APP_SERIAL_HOST) != 0;
        if (h != g.host) { g.host = h; if (h) { char t[TEXT_MAX]; out(T(t, T_BANNER)); } }
        { uint8_t b[16]; while (api->serial_read(APP_SERIAL_USB, b, sizeof b)) if (b[0] == '?') export(); }
        keys();
        turnStep();
        if (!g.phase && due(g.liveT)) {          /* live level, smoothed */
            g.liveT = g.now + LIVE_MS;
            g.live = (int16_t)(g.live + (sample() - g.live) / 2);
            g.dirty = true;
        }
        if (g.msg && g.now - g.msgT >= MSG_MS) { g.msg = false; g.dirty = true; }
        if (g.now - g.batT >= BAT_MS) { g.batT = g.now; api->battery_sample(); g.dirty = true; }
        api->backlight_update();
        if (g.dirty && !g.saver) { g.dirty = false; draw(); }
        api->delay_ms(POLL_MS);
    }
    api->cfg_save((const uint8_t *)&g.cfg, sizeof g.cfg);
    /* both patterns into the display buffers: kept by the loader */
    const uint8_t *src = (const uint8_t *)&sv;
    uint8_t *fb = &api->fb[0][0];
    for (uint16_t i = 0; i < 1024u; i++) {
        const uint8_t v = i < sizeof sv ? src[i] : 0;
        if (i < 128u) api->status_line[i] = v; else fb[i - 128u] = v;
    }
}
