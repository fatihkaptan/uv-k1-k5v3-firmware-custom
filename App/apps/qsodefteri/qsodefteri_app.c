/*
 * QSO Defteri - a logbook on the radio. API level 3. See README.md.
 *
 * MENU opens a new contact: the callsign (multi-tap, upper case), the
 * reports sent and received (59 by default), the VFO frequency and mode (FM,
 * AM or SSB, from the BK4819's AF output) and the UTC time are taken by
 * themselves. A callsign already in the log is flagged (dupe). 50 contacts,
 * kept across restarts: written into the display buffers at exit, which
 * the loader keeps (APP_FLAG_SAVE_SCREEN).
 *
 * The radio has no clock: the time is set from the computer ("/saat <unix>",
 * tools/qsodefteri sends it) or on the keypad (F+1, YYMMDDhhmm), then
 * carried by the tick counter, which counts from power-on. A tick counter
 * found lower than at the last exit means a restart: the time is unknown
 * again ("--:--") until it is set. Contacts logged without a time keep 0.
 *
 * USB: "/liste" sends the log as CSV (call,khz,unix,rst_s,rst_r,mode), F+2
 * too; "/temizle" empties it; tools/qsodefteri/qsodefteri.py writes ADIF.
 */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../app_api.h"
#include "qsodefteri_assets.h"     /* generated by gen_assets.py */

#define NQ        50u      /* contacts in the 1024-byte kept block        */
#define ROWS      5u       /* list rows on screen                         */
#define CALL_MAX  8u
#define POLL_MS   10u
#define TAP_MS    900u
#define LONG_MS   700u
#define BAT_MS    5000u
#define SAVE_MAGIC 0x5144u /* "DQ"                                        */
#define CFG_MAGIC 0x51u
#define BK_REG_47 0x47     /* bits 11:8: the AF output (7 AM, 4/5 SSB)    */
#define NONE      0xFFu

enum { V_LIST, V_FORM, V_TIME };

typedef struct { char call[CALL_MAX]; uint32_t khz, t; uint16_t rs, rr; } qso_t;   /* 20 B */
typedef struct { uint16_t magic; uint8_t n, pad; uint32_t res; qso_t q[NQ]; } log_t;  /* 1008 B */
typedef struct { uint8_t magic, set, pad[2]; uint32_t base, last, res; } cfg_t;      /* 16 B */

static struct {
    uint8_t  view, sel, top, field, raw, key, tapKey, tapIdx, len, fn, confirm, rxLen;
    bool     held, tap, dirty, quit, saver, host, typed, full;
    cfg_t    cfg;
    const app_api_t *A;
    log_t   *L;                        /* on app_main's stack                  */
    qso_t    f;                        /* the contact being written            */
    uint32_t now, keyT, tapT, batT;
    char     in[12];                   /* typed digits (time, reports)         */
    char     rx[24];
} g;

#ifndef HOST_TEST
void *memset(void *d, int c, size_t n) { uint8_t *p = d; while (n) p[--n] = (uint8_t)c; return d; }
void *memcpy(void *d, const void *s, size_t n) {
    uint8_t *p = d; const uint8_t *q = s; while (n) { --n; p[n] = q[n]; } return d;
}
uint64_t __aeabi_uidivmod(uint32_t n, uint32_t d) { return g.A->uidivmod(n, d); }
uint64_t __aeabi_uidiv(uint32_t n, uint32_t d) __attribute__((alias("__aeabi_uidivmod")));
#endif

static char *T(char *b, uint16_t off) { g.A->asset_read(off, b, TEXT_MAX); return b; }
static char *put(char *o, const char *s) { while (*s) *o++ = *s++; *o = '\0'; return o; }
static char *putT(char *o, uint16_t off) { char t[TEXT_MAX]; return put(o, T(t, off)); }
static char *putu(char *o, uint32_t u) { o = g.A->append_u32(o, u); *o = '\0'; return o; }
static char *put2(char *o, uint32_t v) { *o++ = (char)('0' + v / 10u % 10u); *o++ = (char)('0' + v % 10u); *o = '\0'; return o; }
static uint8_t slen(const char *s) { uint8_t n = 0; while (s[n]) n++; return n; }
static char *putCall(char *o, const char *c) { for (uint8_t i = 0; i < CALL_MAX && c[i]; i++) *o++ = c[i]; *o = '\0'; return o; }
static char *putKhz(char *o, uint32_t khz) {         /* "145.500" */
    o = putu(o, khz / 1000u);
    *o++ = '.';
    *o++ = (char)('0' + khz / 100u % 10u);
    return put2(o, khz);
}

/* ---- the clock: UTC seconds = base + ticks / 1000, while the radio stays on ---- */
static uint32_t secs(void) { return g.A->ticks_ms() / 1000u; }
static uint32_t utc(void) { return g.cfg.set ? g.cfg.base + secs() : 0; }
static void setClock(uint32_t t) { g.cfg.base = t - secs(); g.cfg.set = 1; g.dirty = true; }
/* days since 1970-01-01 <-> date (H. Hinnant's algorithms, years 2000+) */
static uint32_t days(uint32_t y, uint32_t m, uint32_t d) {
    y -= m <= 2u;
    const uint32_t era = y / 400u, yoe = y - era * 400u;
    const uint32_t doy = (153u * (m > 2u ? m - 3u : m + 9u) + 2u) / 5u + d - 1u;
    return era * 146097u + yoe * 365u + yoe / 4u - yoe / 100u + doy - 719468u;
}
/* "2026-11-04 14:32" (full) or "04.11 14:32" */
static char *putTime(char *o, uint32_t t, bool full) {
    uint32_t z = t / 86400u + 719468u, s = t % 86400u;
    const uint32_t era = z / 146097u, doe = z - era * 146097u;
    const uint32_t yoe = (doe - doe / 1460u + doe / 36524u - doe / 146096u) / 365u;
    const uint32_t doy = doe - (365u * yoe + yoe / 4u - yoe / 100u), mp = (5u * doy + 2u) / 153u;
    const uint32_t d = doy - (153u * mp + 2u) / 5u + 1u, m = mp < 10u ? mp + 3u : mp - 9u;
    const uint32_t y = yoe + era * 400u + (m <= 2u);
    if (full) { o = putu(o, y); *o++ = '-'; o = put2(o, m); *o++ = '-'; o = put2(o, d); }
    else { o = put2(o, d); *o++ = '.'; o = put2(o, m); }
    *o++ = ' ';
    o = put2(o, s / 3600u); *o++ = ':';
    return put2(o, s / 60u % 60u);
}

/* ---- the log ---- */
static qso_t *at(uint8_t i) { return &g.L->q[g.L->n - 1u - i]; }   /* 0: the newest */
static bool same(const char *a, const char *b) {
    for (uint8_t i = 0; i < CALL_MAX; i++) { if (a[i] != b[i]) return false; if (!a[i]) break; }
    return true;
}
static uint8_t dupes(const char *c) {
    uint8_t n = 0;
    for (uint8_t i = 0; i < g.L->n; i++) n = (uint8_t)(n + same(g.L->q[i].call, c));
    return n;
}
static uint8_t mode(void) {
    const uint8_t af = (uint8_t)((g.A->bk_read(BK_REG_47) >> 8) & 0x0Fu);
    return af == 7u ? 1u : (af == 4u || af == 5u) ? 2u : 0u;
}
static void del(uint8_t i) {                          /* i: 0 = the newest */
    log_t *L = g.L;
    for (uint8_t k = (uint8_t)(L->n - 1u - i); k + 1u < L->n; k++) L->q[k] = L->q[k + 1u];
    L->n--;
    if (g.sel && g.sel >= L->n) g.sel--;
}

/* ---- USB ---- */
static void out(const char *s) {
    if (!g.host) return;
    g.A->serial_write(APP_SERIAL_USB, s, slen(s));
    g.A->serial_write(APP_SERIAL_USB, "\r\n", 2);
}
static void outT(uint16_t off) { char t[TEXT_MAX]; out(T(t, off)); }
static void export(void) {
    char s[48], *o;
    outT(T_CSV);
    for (uint8_t i = 0; i < g.L->n; i++) {
        const qso_t *q = &g.L->q[i];
        o = putCall(s, q->call); *o++ = ',';
        o = putu(o, q->khz); *o++ = ',';
        o = putu(o, q->t); *o++ = ',';
        o = putu(o, q->rs & 0x3FFu); *o++ = ',';
        o = putu(o, q->rr); *o++ = ',';
        putT(o, (uint16_t)(T_MODE + (q->rs >> 14) * T_MODE_STRIDE));
        out(s);
    }
    outT(T_OK);
}
static void lineIn(void) {
    g.rx[g.rxLen] = '\0';
    const char *s = g.rx;
    if (s[0] != '/') return;
    if (s[1] == 's') {                                /* /saat <unix> */
        uint32_t v = 0;
        for (s += 6; *s >= '0' && *s <= '9'; s++) v = v * 10u + (uint32_t)(*s - '0');
        if (v) { setClock(v); outT(T_OK); }
    } else if (s[1] == 'l') export();
    else if (s[1] == 't') { g.L->n = 0; g.sel = g.top = 0; g.dirty = true; outT(T_OK); }
    else if (s[1] == 'e') outT(T_ECHO);
}
static void usb(void) {
    const app_api_t *A = g.A;
    const bool h = (A->serial_ctl(APP_SERIAL_USB, 0) & APP_SERIAL_HOST) != 0;
    if (h != g.host) { g.host = h; if (h) outT(T_BANNER); }
    uint8_t buf[32];
    uint16_t n;
    while ((n = A->serial_read(APP_SERIAL_USB, buf, sizeof buf)) != 0)
        for (uint16_t i = 0; i < n; i++) {
            const char c = (char)buf[i];
            if (c == '\r' || c == '\n') { if (g.rxLen) lineIn(); g.rxLen = 0; }
            else if (g.rxLen < sizeof g.rx - 1u) g.rx[g.rxLen++] = c;
        }
}

/* ---- the form ---- */
static void openForm(void) {
    if (g.L->n >= NQ) { g.full = true; g.A->play_tone(300, 120); return; }
    memset(&g.f, 0, sizeof g.f);
    g.f.khz = g.A->rx_freq() / 100u;
    g.f.rs = (uint16_t)(59u | (uint16_t)mode() << 14);
    g.f.rr = 59;
    g.field = 0; g.len = 0; g.tap = false; g.typed = false;
    g.view = V_FORM;
}
static void saveForm(void) {
    if (!g.f.call[0]) { g.A->play_tone(300, 120); return; }
    g.f.t = utc();
    g.L->q[g.L->n++] = g.f;
    g.sel = 0; g.top = 0;
    g.view = V_LIST;
    g.A->play_tone(1500, 80);
}
static uint16_t *report(void) { return g.field == 1u ? &g.f.rs : &g.f.rr; }
static void formKey(uint8_t k) {
    if (k <= APP_KEY_9) {
        if (g.field) {                                 /* a report: digits, 3 at most */
            uint16_t *r = report(), v = (uint16_t)(*r & 0x3FFu);
            v = g.typed && v < 100u ? (uint16_t)(v * 10u + k) : k;
            *r = (uint16_t)((*r & 0xC000u) | v);
            g.typed = true;
            return;
        }
        char m[KEYMAP_STRIDE];
        g.A->asset_read((uint16_t)(KEYMAP + k * KEYMAP_STRIDE), m, KEYMAP_STRIDE);
        if (g.tap && g.tapKey == k) {
            if (!m[++g.tapIdx]) g.tapIdx = 0;
            g.f.call[g.len - 1u] = m[g.tapIdx];
        } else if (g.len < CALL_MAX) {
            g.f.call[g.len++] = m[0];
            g.tap = true; g.tapKey = k; g.tapIdx = 0;
        }
        g.tapT = g.now;
        return;
    }
    g.tap = false;
    switch (k) {
    case APP_KEY_UP:   g.field = g.field ? (uint8_t)(g.field - 1u) : 2u; g.typed = false; break;
    case APP_KEY_DOWN: g.field = g.field < 2u ? (uint8_t)(g.field + 1u) : 0; g.typed = false; break;
    case APP_KEY_MENU: saveForm(); break;
    case APP_KEY_EXIT:
        if (g.field) { uint16_t *r = report(); *r = (uint16_t)((*r & 0xC000u) | ((*r & 0x3FFu) / 10u)); g.typed = true; }
        else if (g.len) g.f.call[--g.len] = '\0';
        else g.view = V_LIST;
        break;
    default: break;
    }
}

/* ---- time entry: YYMMDDhhmm ---- */
static void timeKey(uint8_t k) {
    if (k <= APP_KEY_9) { if (g.len < 10u) { g.in[g.len++] = (char)('0' + k); g.in[g.len] = '\0'; } return; }
    if (k == APP_KEY_EXIT) { if (g.len) g.in[--g.len] = '\0'; else g.view = V_LIST; return; }
    if (k != APP_KEY_MENU || g.len != 10u) return;
    uint32_t v[5];
    for (uint8_t i = 0; i < 5u; i++) v[i] = (uint32_t)(g.in[2 * i] - '0') * 10u + (uint32_t)(g.in[2 * i + 1] - '0');
    if (!v[1] || v[1] > 12u || !v[2] || v[2] > 31u || v[3] > 23u || v[4] > 59u) { g.A->play_tone(300, 120); return; }
    setClock(days(2000u + v[0], v[1], v[2]) * 86400u + v[3] * 3600u + v[4] * 60u);
    g.view = V_LIST;
    g.A->play_tone(1500, 80);
}

/* ---- the list ---- */
static void listKey(uint8_t k) {
    if (g.fn) {                                        /* F + key */
        const uint8_t c = g.confirm;
        g.fn = 0; g.confirm = NONE;
        if (k == APP_KEY_1) { g.view = V_TIME; g.len = 0; g.in[0] = '\0'; }
        else if (k == APP_KEY_2) export();
        else if ((k == APP_KEY_3 && g.L->n) || k == APP_KEY_0) {
            if (c != k) { g.fn = 1; g.confirm = k; return; }    /* the same key again: sure */
            if (k == APP_KEY_3) del(g.sel); else { g.L->n = 0; g.sel = g.top = 0; }
        }
        return;
    }
    switch (k) {
    case APP_KEY_UP:   if (g.sel) g.sel--; break;
    case APP_KEY_DOWN: if (g.sel + 1u < g.L->n) g.sel++; break;
    case APP_KEY_MENU: openForm(); break;
    case APP_KEY_F:    g.fn = 1; g.confirm = NONE; break;
    case APP_KEY_EXIT: g.quit = true; break;
    default: break;
    }
    if (g.sel < g.top) g.top = g.sel;
    if (g.sel >= g.top + ROWS) g.top = (uint8_t)(g.sel - ROWS + 1u);
}
static void onPress(uint8_t k) {
    g.dirty = true;
    if (g.view == V_FORM) formKey(k);
    else if (g.view == V_TIME) timeKey(k);
    else listKey(k);
}
static void keys(void) {
    const uint8_t k = g.A->get_key();
    if (k == APP_KEY_SAVER) { g.saver = true; return; }
    g.saver = false;
    if (k == APP_KEY_WAKE) { g.dirty = true; g.raw = g.key = APP_KEY_INVALID; return; }
    if (k != g.raw) { g.raw = k; return; }
    if (k == g.key) {
        if (k != APP_KEY_INVALID && !g.held && g.now - g.keyT >= LONG_MS) {
            g.held = true;                               /* long press: the digit */
            if (g.view == V_FORM && !g.field && k <= APP_KEY_9 && g.tap && g.tapKey == k) {
                g.f.call[g.len - 1u] = (char)('0' + k); g.tap = false; g.dirty = true;
            }
        }
        return;
    }
    g.key = k; g.held = false; g.keyT = g.now;
    if (k != APP_KEY_INVALID) onPress(k);
}

/* ---- screen ---- */
static void title(void) {                           /* DEFTER  23/50  14:32Z  battery */
    const app_api_t *A = g.A;
    char s[24], t[24];
    A->display_clear();
    A->status_clear();
    T(t, T_TITLE);
    A->print_inverse(t, 2, 0, true, true, (uint8_t)(2u + 4u * slen(t)));
    putu(put(putu(s, g.L->n), "/"), NQ);
    A->print_tiny(s, 32, 1, true, true);
    const uint32_t u = utc();
    if (u) { putTime(t, u, false); putT(put(s, t + 6), T_Z); }   /* "dd.mm hh:mm" -> "hh:mmZ" */
    else put(s, "--:--");
    A->print_tiny(s, 58, 1, true, true);
    A->draw_battery();
}
static void detail(const qso_t *q, char *s) {          /* "59/57 FM 04.11 14:32Z" */
    char *o = putu(s, q->rs & 0x3FFu);
    *o++ = '/';
    o = putu(o, q->rr); *o++ = ' ';
    o = putT(o, (uint16_t)(T_MODE + (q->rs >> 14) * T_MODE_STRIDE)); *o++ = ' ';
    if (q->t) putT(putTime(o, q->t, false), T_Z); else put(o, "--");
}
static void drawList(void) {
    const app_api_t *A = g.A;
    char s[40];
    if (!g.L->n) { A->print_normal(T(s, T_EMPTY), 0, 127, 1); A->print_normal(T(s, T_NEWHINT), 0, 127, 3); }
    for (uint8_t r = 0; r < ROWS && g.top + r < g.L->n; r++) {
        const qso_t *q = at((uint8_t)(g.top + r));
        putCall(s, q->call);
        A->print_normal(s, 0, 0, r);
        putKhz(s, q->khz);
        A->print_normal(s, (uint8_t)(127u - 7u * slen(s)), 0, r);
        if (g.top + r == g.sel) for (uint8_t x = 0; x < 128u; x++) A->fb[r][x] ^= 0xFFu;
    }
    if (g.L->n) { detail(at(g.sel), s); A->print_tiny(s, 0, 42, false, true); }
    T(s, g.confirm != NONE ? T_SURE : g.full ? T_FULL : g.fn ? T_FHINT : T_LISTHINT);
    g.full = false;
    A->print_tiny(s, 0, 50, false, true);
}
static void drawForm(void) {
    const app_api_t *A = g.A;
    char s[40], *o;
    for (uint8_t f = 0; f < 3u; f++) {
        s[0] = f == g.field ? '>' : ' ';
        o = putT(s + 1, (uint16_t)(T_FIELD + f * T_FIELD_STRIDE));
        if (!f) {
            o = putCall(o, g.f.call);
            if (g.tap) { *o++ = '_'; *o = '\0'; }
        } else putu(o, f == 1u ? g.f.rs & 0x3FFu : g.f.rr);
        A->print_normal(s, 0, 0, f);
    }
    const uint8_t d = dupes(g.f.call);
    if (g.f.call[0] && d) { o = putu(s, d + 1u); putT(o, T_TEKRAR); A->print_tiny(s, 92, 2, false, true); }
    putT(putT(putKhz(s, g.f.khz), T_MHZ), (uint16_t)(T_MODE + (g.f.rs >> 14) * T_MODE_STRIDE));
    A->print_normal(s, 0, 0, 3);
    const uint32_t u = utc();
    if (u) putT(putTime(s, u, true), T_Z); else T(s, T_NOCLOCK);
    A->print_normal(s, 0, 0, 4);
    A->print_tiny(T(s, T_FORMHINT), 0, 50, false, true);
}
static void drawTime(void) {
    const app_api_t *A = g.A;
    char s[24], *o = s;
    static const char mask[] = "20YY-MM-DD hh:mm";
    A->print_normal(T(s, T_TIME), 0, 127, 0);
    for (uint8_t i = 0, j = 0; mask[i]; i++) {   /* the digits typed so far over the mask */
        const bool digit = mask[i] != '-' && mask[i] != ' ' && mask[i] != ':' && i >= 2u;
        *o++ = digit && j < g.len ? g.in[j++] : mask[i];
    }
    *o = '\0';
    A->print_normal(s, 0, 127, 2);
    A->print_tiny(T(s, T_TIMEHINT), 0, 50, false, true);
}
static void draw(void) {
    title();
    if (g.view == V_FORM) drawForm();
    else if (g.view == V_TIME) drawTime();
    else drawList();
    g.A->blit_status();
    g.A->blit_full();
}

__attribute__((section(".text.entry"), used))
void app_main(const app_api_t *api) {
    log_t log;                          /* on the stack: the overlay holds the code */
    g.A = api; g.L = &log;
    g.raw = g.key = APP_KEY_INVALID;
    g.confirm = NONE;
    api->cfg_load((uint8_t *)&g.cfg, sizeof g.cfg);
    if (g.cfg.magic != CFG_MAGIC) { memset(&g.cfg, 0, sizeof g.cfg); g.cfg.magic = CFG_MAGIC; }
    if (secs() < g.cfg.last) g.cfg.set = 0;            /* the radio restarted: no clock */
    api->asset_read(SAVE, &log, sizeof log);
    if (log.magic != SAVE_MAGIC || log.n > NQ) { log.magic = SAVE_MAGIC; log.n = 0; }
    api->backlight_on();
    g.dirty = true;
    while (!g.quit) {
        g.now = api->ticks_ms();
        usb();
        keys();
        if (g.tap && g.now - g.tapT >= TAP_MS) { g.tap = false; g.dirty = true; }
        if (g.now - g.batT >= BAT_MS) { g.batT = g.now; api->battery_sample(); g.dirty = true; }
        api->backlight_update();
        if (g.dirty && !g.saver) { g.dirty = false; draw(); }
        api->delay_ms(POLL_MS);
    }
    g.cfg.last = secs();
    api->cfg_save((const uint8_t *)&g.cfg, sizeof g.cfg);
    const uint8_t *src = (const uint8_t *)&log;      /* the log: kept by the loader */
    uint8_t *fb = &api->fb[0][0];
    for (uint16_t i = 0; i < 1024u; i++) {
        const uint8_t v = i < sizeof log ? src[i] : 0;
        if (i < 128u) api->status_line[i] = v; else fb[i - 128u] = v;
    }
}
