/*
 * Muzik Kutusu - a music box on the radio's speaker, or on the air on the
 * active VFO when menu 4 (Yayin) is switched on. API level 3. See README.md.
 *
 *   1 Sarkilar   Turkish songs in 53-TET komas, tempo adjustable
 *   2 Piyano     the keypad is a two-octave keyboard (1-0 = C D E F G A B C
 *                D E, * sharp, UP/DOWN octave); a note sounds as long as its
 *                key is held; MENU records, F plays the recording back. The
 *                recording survives restarts: at exit it is written into the
 *                display buffers, which the loader keeps (APP_FLAG_SAVE_SCREEN)
 *   3 Ses        five volume levels
 *   4 Yayin      off at every start; on: songs, piano and USB notes key up
 *                the active VFO (its power, CTCSS/DCS) instead of the speaker,
 *                as the Tone Call app does; unkeyed 2 s after the last note,
 *                when the firmware refuses (band, battery) the speaker plays,
 *                and after TX_MAX_MS of transmission yayin switches off
 *   USB          "n<MIDI note>" plays a note, "x" stops it (the computer side,
 *                tools/muzik/muzik.py, plays .mid files and MIDI keyboards);
 *                notes played on the keypad go to the computer the same way
 *
 * The tone is the firmware's own beep path (prepare_tone, the tone generator
 * frequency in REG_71, the mute in REG_50 through tx_mute), switched without
 * blocking, so notes start and stop on time and last as long as wanted.
 */

#include <stdint.h>
#include <stdbool.h>
#include <stddef.h>
#include "../app_api.h"
#include "muzikkutusu_assets.h"     /* generated by gen_assets.py */

#define NREC      255u    /* recorded events (note or rest, duration)       */
#define REC_MAGIC 0x4B4Du /* "MK"                                           */
#define REC_UNIT  20u     /* ms per recorded duration unit                  */
#define POLL_MS   5u
#define IDLE_MS   2000u   /* speaker amplifier off after this much silence  */
#define BAT_MS    5000u
#define CFG_MAGIC 0x4Du
#define NVOL      5u
#define KB_Y0     24u     /* keyboard: frame lines 3-6                      */
#define KB_Y1     55u
#define REG_70    0x70
#define REG_71    0x71
#define REG_30    0x30
#define REG_30_TX_LINK 0xC3FAu /* BK4819_EnableTXLink                       */
#define REG_30_IDLE    0xC1FEu /* as BK4819_PlaySingleTone leaves it        */
#define REG_70_TONE1   0xC200u /* TX: TONE1 on, tuning gain 66              */
#define TX_LEAD_MS 300u   /* carrier before the first note: squelches open  */
#define TX_MAX_MS  180000u /* time-out: yayin off after 3 min on the air     */
#define NONE      0xFFu

enum { V_MENU, V_SONGS, V_PIANO };
enum { S_NONE, S_SONG, S_REC };
enum { A_OFF, A_SPEAKER, A_TX };

typedef struct { uint8_t magic, vol, oct, song; } cfg_t;
typedef struct { uint16_t magic; uint8_t n, pad; uint8_t ev[2u * NREC]; } rec_t;   /* the saved block */

static struct {
    uint8_t  view, sel, cur, last, raw, key, src, pos, len, bpm, kn, tempo, rxLen, played, audio;
    bool     held, dirty, quit, saver, sharp, rec, host, tx, cr, pc;
    cfg_t    cfg;
    const app_api_t *A;
    rec_t   *R;                        /* on app_main's stack                    */
    uint32_t now, keyT, evAt, gapAt, recT, idleT, batT, txT;
    uint16_t notes, pal, dur, reg;     /* song: notes, pitches, lengths; REG_71  */
    char     rx[8];
} g;

#ifndef HOST_TEST
void *memset(void *d, int c, size_t n) { uint8_t *p = d; while (n) p[--n] = (uint8_t)c; return d; }
void *memcpy(void *d, const void *s, size_t n) {
    uint8_t *p = d; const uint8_t *q = s; while (n) { --n; p[n] = q[n]; } return d;
}
uint64_t __aeabi_uidivmod(uint32_t n, uint32_t d) { return g.A->uidivmod(n, d); }
uint64_t __aeabi_uidiv(uint32_t n, uint32_t d) __attribute__((alias("__aeabi_uidivmod")));
#endif

static char *T(char *b, uint16_t off) { g.A->asset_read(off, b, TEXT_MAX); return b; }
static char *put(char *o, const char *s) { while (*s) *o++ = *s++; *o = '\0'; return o; }
static char *putT(char *o, uint16_t off) { char t[TEXT_MAX]; return put(o, T(t, off)); }
static char *putu(char *o, uint32_t u) { o = g.A->append_u32(o, u); *o = '\0'; return o; }
static uint8_t slen(const char *s) { uint8_t n = 0; while (s[n]) n++; return n; }
static bool due(uint32_t t) { return (int32_t)(g.now - t) >= 0; }
static uint8_t rd8(uint16_t off) { uint8_t b; g.A->asset_read(off, &b, 1); return b; }
static uint16_t songAt(uint8_t i) {             /* asset offset of song i */
    uint16_t o; g.A->asset_read((uint16_t)(SONG_OFF + 2u * i), &o, 2); return (uint16_t)(SONG + o);
}

/* ---- USB ---- */
static void send(const char *s) {
    if (g.host) g.A->serial_write(APP_SERIAL_USB, s, slen(s));
}
static void sendNote(uint8_t n) {               /* "n60\r\n" or "x\r\n" */
    char s[8], *o = s;
    if (n) { *o++ = 'n'; o = putu(o, n); } else *o++ = 'x';
    put(o, "\r\n");
    send(s);
}

/* ---- tone: the beep path, switched by the mute ---- */
static void volume(void) {
    static const uint8_t gain[NVOL] = { 6, 12, 24, 40, 64 };
    g.A->bk_write(REG_70, (uint16_t)(0x8000u | gain[g.cfg.vol] << 8));
}
static void noteOff(void) {
    if (!g.cur) return;
    g.A->tx_mute(true);
    g.cur = 0; g.idleT = g.now; g.dirty = true;
}
static void quiet(void) {                       /* speaker off / unkey, back to RX */
    const app_api_t *A = g.A;
    if (g.audio == A_TX) {                      /* as the Tone Call app ends a call */
        A->bk_write(REG_70, 0);
        A->bk_write(REG_30, REG_30_IDLE);
        A->tx_mute(true);
        A->tx_end();
        A->led(false);
    } else if (g.audio) {
        A->tones_off_rx();
        A->audio_path(false);
    }
    g.audio = A_OFF;
}
/* The speaker, or the active VFO when yayin is on (not in the menu: the
 * volume sample stays local) and the firmware allows it right now. */
static void tone(uint16_t r, uint8_t n) {       /* REG_71 value, the key drawn */
    const app_api_t *A = g.A;
    const uint8_t want = g.tx && g.view != V_MENU && !A->tx_state() ? A_TX : A_SPEAKER;
    if (g.audio != want) {
        quiet();
        if (want == A_TX) {                     /* key up: carrier, PA, CTCSS/DCS */
            A->tx_set_params();
            A->tx_mute(true);
            A->set_af(APP_AF_MUTE);
            A->bk_write(REG_70, REG_70_TONE1);
            A->bk_write(REG_30, REG_30_TX_LINK);
            A->led(true);
            A->delay_ms(TX_LEAD_MS);
            g.evAt += TX_LEAD_MS; g.txT = g.now;
        } else { A->prepare_tone(); volume(); A->audio_path(true); }
        g.audio = want;
    }
    A->bk_write(REG_71, r);
    A->tx_mute(false);
    g.reg = r; g.cur = g.last = n; g.dirty = true;
}
static void noteOn(uint8_t n) {
    if (!n) { noteOff(); return; }
    while (n < NOTE_LO) n = (uint8_t)(n + 12u);
    while (n > NOTE_HI) n = (uint8_t)(n - 12u);
    uint16_t r;
    g.A->asset_read((uint16_t)(TONE + 2u * (n - NOTE_LO)), &r, 2);
    g.kn = 0;
    tone(r, n);
}
static void pitchOn(uint8_t p) {                /* a song's pitch: piano note or 53-TET */
    if (p < NTONE) { noteOn((uint8_t)(NOTE_LO + p)); return; }
    p = (uint8_t)(p - NTONE);
    uint16_t r;
    g.A->asset_read((uint16_t)(KREG + 2u * p), &r, 2);
    g.kn = (uint8_t)(p + 1u);
    tone(r, rd8((uint16_t)(KMIDI + p)));
}

/* ---- sequencer: a song from the assets or the recording ---- */
static void seqStop(void) { g.src = S_NONE; noteOff(); g.dirty = true; }
static void seqStart(uint8_t src) {
    noteOff();
    g.src = src; g.pos = 0; g.evAt = g.now; g.gapAt = 0; g.dirty = true;
    if (src == S_REC) { g.len = g.R->n; return; }
    uint8_t h[5];
    const uint16_t at = songAt(g.cfg.song);
    g.A->asset_read(at, h, 5);
    g.bpm = h[0]; g.len = h[1];
    char t[TEXT_MAX];
    g.pal = (uint16_t)(at + 5u + slen(T(t, (uint16_t)(at + 5u))) + 1u);
    g.dur = (uint16_t)(g.pal + h[3]);
    g.notes = (uint16_t)(g.dur + 2u * h[4]);
}
static void seqStep(void) {
    if (!g.src) return;
    if (g.gapAt && due(g.gapAt)) { noteOff(); g.gapAt = 0; }
    if (!due(g.evAt)) return;
    if (g.pos >= g.len) { seqStop(); return; }
    uint32_t ms;
    if (g.src == S_SONG) {
        const uint8_t e = rd8((uint16_t)(g.notes + g.pos));
        uint16_t d;
        g.A->asset_read((uint16_t)(g.dur + 2u * (e & 15u)), &d, 2);
        ms = (uint32_t)d * 100u / g.tempo;
        if ((e >> 4) == 15u) noteOff(); else pitchOn(rd8((uint16_t)(g.pal + (e >> 4))));
        g.evAt += ms;
        g.gapAt = g.evAt - ms / 8u;             /* detached: silent for the last eighth */
    } else {
        noteOn(g.R->ev[2u * g.pos]);
        g.evAt += (uint32_t)g.R->ev[2u * g.pos + 1u] * REC_UNIT;
    }
    g.pos++;
    g.dirty = true;
}

/* ---- recording ---- */
static void recAdd(uint8_t n, uint32_t ms) {
    rec_t *R = g.R;
    if (R->n >= NREC) { g.rec = false; return; }
    uint32_t d = (ms + REC_UNIT / 2u) / REC_UNIT;
    R->ev[2u * R->n] = n;
    R->ev[2u * R->n + 1u] = (uint8_t)(d < 1u ? 1u : d > 255u ? 255u : d);
    R->n++;
}

/* ---- the computer's lines: n<note>, x, /echo off ---- */
static void lineIn(void) {
    g.rx[g.rxLen] = '\0';
    if (g.rx[0] == 'n' && !g.src) {
        uint8_t n = 0;
        for (const char *p = g.rx + 1; *p >= '0' && *p <= '9'; p++) n = (uint8_t)(n * 10u + (uint8_t)(*p - '0'));
        if (g.view == V_MENU) g.view = V_PIANO;
        g.pc = true;
        noteOn(n);
    } else if (g.rx[0] == 'x') noteOff();
    else if (g.rx[0] == '/' && g.rx[1] == 'e') { char t[TEXT_MAX]; send(T(t, T_ECHO)); send("\r\n"); }
}
static void usb(void) {
    const app_api_t *A = g.A;
    const bool h = (A->serial_ctl(APP_SERIAL_USB, 0) & APP_SERIAL_HOST) != 0;
    if (h != g.host) {
        g.host = h; g.dirty = true;
        if (h) { char t[TEXT_MAX]; send(T(t, T_BANNER)); send("\r\n"); }
    }
    uint8_t buf[32];
    uint16_t n;
    while ((n = A->serial_read(APP_SERIAL_USB, buf, sizeof buf)) != 0)
        for (uint16_t i = 0; i < n; i++) {
            const char c = (char)buf[i];
            if (c == '\r' || c == '\n') { if (g.rxLen) lineIn(); g.rxLen = 0; }
            else if (g.rxLen < sizeof g.rx - 1u) g.rx[g.rxLen++] = c;
        }
}

/* ---- keys ---- */
static uint8_t keyNote(uint8_t k) {             /* 1-9, 0 -> C D E F G A B C D E */
    static const uint8_t step[10] = { 16, 0, 2, 4, 5, 7, 9, 11, 12, 14 };
    return (uint8_t)(12u * (g.cfg.oct + 1u) + step[k]);
}
static void release(uint8_t k) {                /* a piano key let go */
    if (g.view != V_PIANO || k > APP_KEY_9 || g.src || !g.played) return;
    if (g.rec) { recAdd(g.played, g.now - g.recT); g.recT = g.now; }
    g.played = 0;
    noteOff();
    sendNote(0);
}
static void pianoKey(uint8_t k) {
    if (k <= APP_KEY_9) {
        if (g.src) return;
        const uint8_t n = (uint8_t)(keyNote(k) + g.sharp);
        g.sharp = false;
        if (g.rec) { if (g.R->n) recAdd(0, g.now - g.recT); g.recT = g.now; }
        g.played = n; g.pc = false;
        noteOn(n);
        sendNote(n);
        return;
    }
    switch (k) {
    case APP_KEY_STAR: g.sharp = !g.sharp; break;
    case APP_KEY_UP:   if (g.cfg.oct < 6u) g.cfg.oct++; break;
    case APP_KEY_DOWN: if (g.cfg.oct > 3u) g.cfg.oct--; break;
    case APP_KEY_MENU:                          /* record: a new take */
        if (g.src) break;
        g.rec = !g.rec;
        if (g.rec) { g.R->n = 0; g.recT = g.now; }
        break;
    case APP_KEY_F:
        g.rec = false;
        if (g.src) seqStop(); else if (g.R->n) seqStart(S_REC);
        break;
    case APP_KEY_EXIT:
        if (g.src) seqStop(); else { g.rec = false; g.view = V_MENU; }
        break;
    default: break;
    }
}
static void songKey(uint8_t k) {
    if (k >= APP_KEY_1 && k <= APP_KEY_9 && k < APP_KEY_1 + NSONG) { g.cfg.song = (uint8_t)(k - APP_KEY_1); g.tempo = 100; seqStart(S_SONG); return; }
    switch (k) {
    case APP_KEY_UP:
    case APP_KEY_DOWN:
        if (g.src) {                            /* tempo, 50 .. 200 % */
            g.tempo = (uint8_t)(k == APP_KEY_UP ? (g.tempo < 200u ? g.tempo + 10u : 200u)
                                                : (g.tempo > 50u ? g.tempo - 10u : 50u));
        } else if (k == APP_KEY_DOWN) g.cfg.song = g.cfg.song + 1u < NSONG ? (uint8_t)(g.cfg.song + 1u) : 0;
        else g.cfg.song = g.cfg.song ? (uint8_t)(g.cfg.song - 1u) : NSONG - 1u;
        break;
    case APP_KEY_MENU: if (g.src) seqStop(); else { g.tempo = 100; seqStart(S_SONG); } break;
    case APP_KEY_EXIT: if (g.src) seqStop(); else g.view = V_MENU; break;
    default: break;
    }
}
static void onPress(uint8_t k) {
    g.dirty = true;
    if (g.view == V_PIANO) { pianoKey(k); return; }
    if (g.view == V_SONGS) { songKey(k); return; }
    if (k == APP_KEY_EXIT) { g.quit = true; return; }
    if (k == APP_KEY_UP) g.sel = g.sel ? (uint8_t)(g.sel - 1u) : 3u;
    else if (k == APP_KEY_DOWN) g.sel = g.sel < 3u ? (uint8_t)(g.sel + 1u) : 0;
    else if (k >= APP_KEY_1 && k <= APP_KEY_4) g.sel = (uint8_t)(k - APP_KEY_1);
    if (k == APP_KEY_MENU || (k >= APP_KEY_1 && k <= APP_KEY_4)) {
        if (g.sel == 3u) g.tx = !g.tx;
        else if (g.sel == 2u) { g.cfg.vol = (uint8_t)((g.cfg.vol + 1u) % NVOL); noteOn(72); g.gapAt = g.now + 150u; g.src = 0; }
        else g.view = (uint8_t)(V_SONGS + g.sel);
    }
}
static void keys(void) {
    const uint8_t k = g.A->get_key();
    if (k == APP_KEY_SAVER) { g.saver = true; return; }
    g.saver = false;
    if (k == APP_KEY_WAKE) { g.dirty = true; g.raw = g.key = APP_KEY_INVALID; return; }
    if (k != g.raw) { g.raw = k; return; }      /* debounce: two equal readings */
    if (k == g.key) return;
    release(g.key);
    g.key = k; g.keyT = g.now;
    if (k != APP_KEY_INVALID) onPress(k);
}

/* ---- screen ---- */
static void title(const char *t) {
    const app_api_t *A = g.A;
    A->display_clear();
    A->status_clear();
    A->print_inverse(t, 2, 0, true, true, (uint8_t)(2u + 4u * slen(t)));
    A->draw_battery();
}
static void capsule(uint16_t off) {
    char t[TEXT_MAX];
    T(t, off);                                  /* before slen(t): argument order is unspecified */
    g.A->print_inverse(t, 62, 0, true, true, (uint8_t)(62u + 4u * slen(t)));
}
static void fill(uint8_t x0, uint8_t x1, uint8_t y0, uint8_t y1, bool xor) {
    for (uint8_t x = x0; x <= x1; x++)
        for (uint8_t y = y0; y <= y1; y++) {
            uint8_t *b = &g.A->fb[y >> 3][x];
            const uint8_t m = (uint8_t)(1u << (y & 7u));
            *b = xor ? (uint8_t)(*b ^ m) : (uint8_t)(*b | m);
        }
}
static char *noteName(char *o, uint8_t n) {
    if (g.kn && n == g.cur) return putT(o, (uint16_t)(KNAME + (g.kn - 1u) * KNAME_STRIDE));
    o = putT(o, (uint16_t)(T_NOTE + (n % 12u) * T_NOTE_STRIDE));
    return putu(o, n / 12u - 1u);
}
static char *hzOf(char *o) {                    /* the tone's Hz, from REG_71 */
    return putT(putu(o, ((uint32_t)g.reg * 131072u + 676622u) / 1353245u), T_HZ);
}
/* Two octaves from base (a C), keys 9 px wide; key i: x 9i+1 .. 9i+8. The
 * keypad digits under the first ten white keys; hl is drawn inverted. */
static void keyboard(uint8_t base, uint8_t hl) {
    static const uint8_t white[12] = { 0, 0, 1, 1, 2, 3, 3, 4, 4, 5, 5, 6 };
    for (uint8_t i = 0; i <= 14u; i++) fill((uint8_t)(9u * i), (uint8_t)(9u * i), KB_Y0, KB_Y1, false);
    fill(0, 126, KB_Y0, KB_Y0, false);
    fill(0, 126, KB_Y1, KB_Y1, false);
    for (uint8_t i = 0; i < 10u; i++) {
        const char d[2] = { (char)(i < 9u ? '1' + i : '0'), 0 };
        g.A->print_tiny(d, (uint8_t)(9u * i + 3u), 47, false, true);
    }
    for (uint8_t s = 0; s < 24u; s++) {
        const uint8_t o = s >= 12u, t = (uint8_t)(s - 12u * o), b = (uint8_t)(9u * (7u * o + white[t] + 1u));
        const bool black = (0x54Au >> t) & 1u;
        if (black) fill((uint8_t)(b - 2u), (uint8_t)(b + 2u), KB_Y0, 41, false);
        if ((uint8_t)(hl - base) != s) continue;
        if (black) fill((uint8_t)(b - 1u), (uint8_t)(b + 1u), KB_Y0 + 1u, 40, true);
        else fill((uint8_t)(b - 8u), (uint8_t)(b - 1u), 43, KB_Y1 - 1u, true);
    }
}
static void drawMenu(void) {
    char s[24], t[TEXT_MAX];
    title(T(t, T_TITLE));
    for (uint8_t i = 0; i < 4u; i++) {
        s[0] = (char)('1' + i); s[1] = ' ';
        char *o = putT(s + 2, (uint16_t)(T_MENU + i * T_MENU_STRIDE));
        if (i == 2u) for (uint8_t v = 0; v < NVOL; v++) *o++ = v <= g.cfg.vol ? '#' : '.';
        *o = '\0';
        if (i == 3u) putT(o, g.tx ? T_TXON : T_TXOFF);
        g.A->print_normal(s, 0, 0, i);
        if (i == g.sel) for (uint8_t x = 0; x < 128u; x++) g.A->fb[i][x] ^= 0xFFu;
    }
    g.A->print_tiny(T(t, g.tx ? T_TXWARN : T_USB), 0, 42, false, true);
    g.A->print_tiny(T(t, T_HINT), 0, 50, false, true);
}
static void drawSongs(void) {
    const app_api_t *A = g.A;
    char s[32], t[TEXT_MAX];
    title(T(t, T_TITLE));
    const uint16_t at = songAt(g.cfg.song);
    const uint8_t mk = rd8((uint16_t)(at + 2u));
    /* the makam in the status-line capsule (the frame has no line 7: text
     * drawn below y 55 lands in the status line) */
    const uint16_t mko = mk ? (uint16_t)(T_MAKAM + mk * T_MAKAM_STRIDE) : T_PLAY;
    if (!g.src) {                               /* the list: tiny number, title */
        const uint8_t top = g.cfg.song > 6u ? (uint8_t)(g.cfg.song - 6u) : 0;
        for (uint8_t r = 0; r < 7u && top + r < NSONG; r++) {
            const uint8_t i = (uint8_t)(top + r);
            putu(s, i + 1u);
            A->print_tiny(s, 0, (uint8_t)(8u * r + 1u), false, true);
            A->print_normal(T(t, (uint16_t)(songAt(i) + 5u)), 10, 0, r);
            if (i == g.cfg.song) for (uint8_t x = 0; x < 128u; x++) A->fb[r][x] ^= 0xFFu;
        }
        if (mk) capsule(mko);
        return;
    }
    capsule(mko);
    A->print_normal(T(t, (uint16_t)(at + 5u)), 0, 0, 0);
    char *o = s;
    if (g.cur) o = put(noteName(s, g.cur), "  ");
    putT(putu(o, (uint32_t)g.bpm * g.tempo / 100u), T_BPM);
    A->print_normal(s, 0, 0, 1);
    fill(0, (uint8_t)(126u * g.pos / g.len), 18, 20, false);   /* progress */
    keyboard(60, g.cur);
}
static void drawPiano(void) {
    const app_api_t *A = g.A;
    char s[24], t[TEXT_MAX];
    title(T(t, T_TITLE));
    if (g.rec) capsule(T_REC);
    else if (g.src) capsule(T_PLAY);
    else if (g.pc && g.cur) capsule(T_PC);
    if (g.sharp) A->print_inverse("#", 80, 0, true, true, 84);
    const uint8_t n = g.cur ? g.cur : g.last;
    if (n) {
        noteName(s, n);
        A->print_string(s, 2, 0, 0, 10);        /* big, lines 0-1 */
        hzOf(s);
        A->print_normal(s, 48, 0, 0);
    }
    putu(putT(s, T_OCT), g.cfg.oct);
    A->print_normal(s, 48, 0, 1);
    if (g.R->n || g.rec) putT(putu(putT(s, T_RECN), g.R->n), T_NOTA);
    else T(s, T_PIANOHINT);
    A->print_tiny(s, 0, 17, false, true);
    keyboard((uint8_t)(12u * (g.cfg.oct + 1u)), g.cur);
}
static void draw(void) {
    if (g.view == V_MENU) drawMenu();
    else if (g.view == V_SONGS) drawSongs();
    else drawPiano();
    if (g.audio == A_TX) g.A->print_inverse("TX", 100, 0, true, true, 108);
    g.A->blit_status();
    g.A->blit_full();
}

/* The recording, into the display buffers: the loader keeps them in the
 * last 1024 bytes of the assets (APP_FLAG_SAVE_SCREEN). */
static void save(void) {
    const uint8_t *s = (const uint8_t *)g.R;
    const uint16_t size = (uint16_t)(4u + 2u * g.R->n);
    uint8_t *fb = &g.A->fb[0][0];
    for (uint16_t i = 0; i < 1024u; i++) {
        const uint8_t v = i < size ? s[i] : 0;
        if (i < 128u) g.A->status_line[i] = v; else fb[i - 128u] = v;
    }
}

__attribute__((section(".text.entry"), used))
void app_main(const app_api_t *api) {
    rec_t rec;                          /* on the stack: the overlay holds the code */
    g.A = api; g.R = &rec;
    g.raw = g.key = APP_KEY_INVALID;
    api->cfg_load((uint8_t *)&g.cfg, sizeof g.cfg);
    if (g.cfg.magic != CFG_MAGIC || g.cfg.vol >= NVOL || g.cfg.oct < 3u || g.cfg.oct > 6u || g.cfg.song >= NSONG) {
        g.cfg.magic = CFG_MAGIC; g.cfg.vol = 2; g.cfg.oct = 4; g.cfg.song = 0;
    }
    api->asset_read(SAVE, &rec, sizeof rec);
    if (rec.magic != REC_MAGIC) { rec.magic = REC_MAGIC; rec.n = 0; }   /* first run: zeros */
    g.tempo = 100;
    api->backlight_on();
    g.dirty = true;
    while (!g.quit) {
        g.now = api->ticks_ms();
        usb();
        keys();
        seqStep();
        if (g.audio && !g.cur && !g.src && g.now - g.idleT >= IDLE_MS) quiet();
        if (g.audio == A_TX && g.now - g.txT >= TX_MAX_MS) { g.tx = false; seqStop(); quiet(); }
        if (g.gapAt && !g.src && due(g.gapAt)) { noteOff(); g.gapAt = 0; }   /* the volume sample */
        if (g.now - g.batT >= BAT_MS) { g.batT = g.now; api->battery_sample(); g.dirty = true; }
        api->backlight_update();
        if (g.dirty && !g.saver) { g.dirty = false; draw(); }
        api->delay_ms(POLL_MS);
    }
    noteOff();
    quiet();
    api->cfg_save((const uint8_t *)&g.cfg, sizeof g.cfg);
    save();
}
