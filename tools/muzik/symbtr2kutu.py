#!/usr/bin/env python3
# SymbTr -> Muzik Kutusu: writes App/apps/muzikkutusu/sarkilar/turkuler.txt,
# the Turkish songs of the music box, from the SymbTr database of Turkish
# makam music (txt scores, pitch in 53-TET komas):
#
#   M. Kemal Karaosmanoglu, "A Turkish makam music symbolic database for
#   music information retrieval: SymbTr", ISMIR 2012.
#   https://github.com/MTG/SymbTr  (CC BY-NC-SA 4.0)
#
# The note data written is derived from SymbTr, so it carries the same
# license (non-commercial, share alike, with this attribution). Only
# anonymous folk songs (turku) and pieces of composers dead for more than
# 70 years are taken; lyrics are not copied, only pitch and duration.
#
#   git clone --depth 1 https://github.com/MTG/SymbTr
#   python3 tools/muzik/symbtr2kutu.py SymbTr/txt > App/apps/muzikkutusu/sarkilar/turkuler.txt
#
# Each song is an excerpt (the first verse, from the first sung syllable),
# chosen to fit the asset space of the app. The pitch is the Koma53 column,
# spelled like the Nota53 column with letters: "F5#3" = F5 raised 3 komas.
import os, statistics, sys
from fractions import Fraction

# (file, title <= 16 ASCII, makam shown, first event, end event) - events
# counted after dropping grace notes and markers; first None = the first
# sung syllable.
SONGS = [
    ("segah--turku--aksak--beyaz_giyme--bolu", "Beyaz Giyme", "Segah", None, 122),
    ("nihavent--turku--nimsofyan--uskudara_gider--", "Uskudar'a Gider", "Nihavent", None, 153),
    ("hicaz--turku--devrihindi--cayelinden_oteye--rize", "Cayelinden", "Hicaz", None, 81),
    ("hicaz--turku--yuruksemai_ii--bitliste_bes--", "Bitlis'te Bes", "Hicaz", None, 114),
    ("hicaz--rumeliturkusu--sofyan--kirmizi_gulun--rumeli", "Kirmizi Gulun", "Hicaz", None, 151),
    ("hicaz--turku--nimsofyan--erkilet_guzeli--", "Erkilet Guzeli", "Hicaz", None, 160),
    ("neva--turku--sofyan--canakkale_icinde--", "Canakkale", "Neva", None, 153),
    ("huseyni--turku--curcuna--sari_gelin--erzurum", "Sari Gelin", "Huseyni", None, 83),
    ("huseyni--turku--sofyan--hey_onbesli--tokat", "Hey Onbesli", "Huseyni", None, 144),
    ("beyati--turku--nimsofyan--gesi_baglarinda--kayseri", "Gesi Baglari", "Beyati", None, 121),
    ("huseyni--mars--sofyan--ceddin_deden--kaptanzade_ali_riza_bey", "Ceddin Deden", "Huseyni", None, 125),
]
SKIP = {8, 35, 50, 51, 53, 54, 55}        # grace notes (no duration), usul and section markers
NOT_SUNG = {"", ".", "SAZ", "ARANAĞME", "ARANAGME"}
SOLFEGE = {"Do": "C", "Re": "D", "Mi": "E", "Fa": "F", "Sol": "G", "La": "A", "Si": "B"}
NATURAL = {"C": 0, "D": 9, "E": 18, "F": 22, "G": 31, "A": 40, "B": 49}   # komas above C


def events(path):
    """(koma or -1 for a rest, Nota53 spelling, duration as a whole-note
    fraction, ms, sung syllable?) for each note or rest."""
    out = []
    with open(path, encoding="utf-8") as f:
        next(f)
        for line in f:
            r = line.rstrip("\n").split("\t")
            if len(r) < 12 or not r[1].isdigit() or int(r[1]) in SKIP:
                continue
            pay, payda = int(r[6] or 0), int(r[7] or 0)
            if pay <= 0 or payda <= 0:
                continue
            koma = int(r[4]) if r[4].lstrip("-").isdigit() else -1
            rest = r[2] in ("Es", "") or koma < 0
            out.append((-1 if rest else koma, r[2], Fraction(pay, payda), int(r[8] or 0),
                        r[11].strip() not in NOT_SUNG))
    return out


def spell(nota53, koma):
    """'Fa5#3' -> 'F5#3' (checked against the koma), 'Sol5' -> 'G5'."""
    i = 3 if nota53.startswith("Sol") else 2
    letter, rest = SOLFEGE[nota53[:i]], nota53[i:]
    octave, acc = int(rest[0]), rest[1:]
    k = 265 + 53 * (octave - 4) + NATURAL[letter] + (int(acc[1:]) * (1 if acc[0] == "#" else -1) if acc else 0)
    if k != koma:
        sys.exit(f"{nota53}: {k} komas, the score says {koma}")
    return f"{letter}{octave}{acc}"


def dur(fr):
    """1/8 -> '/8', 3/16 -> '/8.', 5/8 -> '*5/8'."""
    if fr.numerator == 1:
        return f"/{fr.denominator}"
    if fr.numerator == 3 and fr.denominator % 2 == 0:
        return f"/{fr.denominator // 2}."
    return f"*{fr.numerator}/{fr.denominator}"


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: symbtr2kutu.py <SymbTr/txt directory> > turkuler.txt")
    src = sys.argv[1]
    print("# Muzik Kutusu - Turkish songs (turku, hicaz ...), 53-TET komas.")
    print("# Derived from SymbTr: M. Kemal Karaosmanoglu, \"A Turkish makam music symbolic")
    print("# database for music information retrieval: SymbTr\", ISMIR 2012,")
    print("# https://github.com/MTG/SymbTr - licensed CC BY-NC-SA 4.0")
    print("# (https://creativecommons.org/licenses/by-nc-sa/4.0/): this file is too.")
    print("# Generated by tools/muzik/symbtr2kutu.py; excerpts, pitch and duration only.")
    print("# Format: see gen_assets.py.")
    for name, title, makam, first, end in SONGS:
        ev = events(os.path.join(src, name + ".txt"))
        if first is None:
            first = next(i for i, e in enumerate(ev) if e[4] and e[0] >= 0)
        part = ev[first:end]
        while part and part[-1][0] < 0:              # no trailing rests
            part.pop()
        whole = statistics.median(e[3] / e[2] for e in part if e[3])     # ms per whole note
        bpm = round(240000 / whole)
        print(f"\n# {name}.txt, events {first}..{first + len(part) - 1}")
        print(f"= {title} | {makam} | {bpm}")
        toks = [("R" if k < 0 else spell(n, k)) + dur(fr) for k, n, fr, _, _ in part]
        for i in range(0, len(toks), 12):
            print(" ".join(toks[i:i + 12]))


if __name__ == "__main__":
    main()
